//! The audio capability's authored-content SCHEMA registrations.
//!
//! Two files, two concerns, deliberately not one schema: `music_registry.ron`
//! points at pre-rendered OGGs, `sfx_registry.ron` describes procedural synth
//! cues. They are separate on disk for that reason and stay separate here.
//!
//! ## These reuse `validate()`, they do not re-implement it
//!
//! ⚠ [`MusicRegistry::validate`] and [`SfxRegistry::validate`] already exist and
//! already run — `AudioCatalogFragment::new` calls them at App-build time. A
//! handler that re-derived those rules would be a SECOND validator for one
//! file, which is the exact defect this crate exists to remove, reintroduced
//! inside it. So the handlers call the same method and map its message.
//!
//! What migrating buys, then, is not "validation where there was none":
//!
//! * the same rules run **without building an App** — in the CLI, in CI, in
//!   milliseconds, with the file's name and a fix line attached;
//! * `deny_unknown_fields`, which `validate()` cannot see because serde has
//!   already dropped an unknown field by the time it runs;
//! * **asset provenance** — every track's OGG becomes a declared requirement,
//!   which nothing checked before. `AudioCatalogFragment` validates the shape of
//!   the registry and never asks whether the files it points at exist;
//! * `music_track` identities, so a future room-music reference can RESOLVE
//!   against them instead of being cross-checked by hand in
//!   `content_validation.rs`.
//!
//! ## `music_registry.ron` is GENERATED
//!
//! ⛔ By `scripts/regen_music_registry.py`. A refusal here is a bug in the
//! GENERATOR or in the asset tree, never something to hand-fix in the file —
//! the next render overwrites it. The fix lines say so.

use std::sync::Arc;

use ambition_content_pack::{
    AssetRequirement, CapabilityId, ContentSchemaHandler, DiagnosticCode, FacetOutcome,
    FacetSource, RuntimeDisposition, SchemaId, SchemaRegistration, SchemaVersion,
};

use crate::spec::{MusicRegistry, SfxRegistry};

/// The capability that owns both schemas here.
pub const AUDIO_CAPABILITY: &str = "audio";

pub const MUSIC_REGISTRY_SCHEMA: &str = "music_registry";
/// One playable track.
pub const MUSIC_TRACK_SCHEMA: &str = "music_track";
pub const SFX_REGISTRY_SCHEMA: &str = "sfx_registry";
/// One procedural cue.
pub const SFX_CUE_SCHEMA: &str = "sfx_cue";

pub const MUSIC_REGISTRY_VERSION: SchemaVersion = SchemaVersion(1);
pub const SFX_REGISTRY_VERSION: SchemaVersion = SchemaVersion(1);

fn canonical<T: std::fmt::Debug>(value: &T) -> String {
    format!("{value:?}")
}

fn code_for(error: &ron::error::SpannedError) -> DiagnosticCode {
    match error.code {
        ron::error::Error::NoSuchStructField { .. } => DiagnosticCode::UnknownField,
        _ => DiagnosticCode::MalformedSource,
    }
}

// ── music ────────────────────────────────────────────────────────────────────

struct MusicRegistrySchema;

impl ContentSchemaHandler for MusicRegistrySchema {
    fn check(&self, facet: &FacetSource<'_>, out: &mut FacetOutcome) {
        let registry: MusicRegistry = match ron::from_str(facet.text) {
            Ok(registry) => registry,
            Err(error) => {
                out.report(
                    facet
                        .diagnostic(code_for(&error), format!("{error}"))
                        .fix(GENERATED_FIX),
                );
                return;
            }
        };

        // The ONE validator, not a second copy of its rules.
        if let Err(message) = registry.validate() {
            out.report(
                facet
                    .diagnostic(DiagnosticCode::MalformedProviderBinding, message)
                    .fix(GENERATED_FIX),
            );
        }

        for track in &registry.tracks {
            let id = facet.content_id_in(MUSIC_TRACK_SCHEMA, &track.id);
            out.define(id.clone(), canonical(track));
            // The asset half nothing checked before: `AudioCatalogFragment`
            // validates the registry's SHAPE and never asks whether the OGG it
            // points at is there.
            out.need_asset(AssetRequirement::new(
                track.resolved_asset_path(),
                id,
                "asset_path",
            ));
        }

        if !out.failed() {
            out.lower(registry);
        }
    }
}

const GENERATED_FIX: &str =
    "⛔ `music_registry.ron` is GENERATED by scripts/regen_music_registry.py — fix the generator \
     or the asset tree, not this file, because the next render overwrites it";

// ── sfx ──────────────────────────────────────────────────────────────────────

struct SfxRegistrySchema;

impl ContentSchemaHandler for SfxRegistrySchema {
    fn check(&self, facet: &FacetSource<'_>, out: &mut FacetOutcome) {
        let registry: SfxRegistry = match ron::from_str(facet.text) {
            Ok(registry) => registry,
            Err(error) => {
                out.report(facet.diagnostic(code_for(&error), format!("{error}")));
                return;
            }
        };

        if let Err(message) = registry.validate() {
            out.report(facet.diagnostic(DiagnosticCode::MalformedProviderBinding, message));
        }

        // A procedural cue has no asset — it IS the synthesis spec. Identities
        // still matter so a caller can name what a provider authorized.
        for spec in &registry.sfx {
            // Named by what the AUTHOR wrote — the open `id` string, or the
            // typed cue — not by the hashed `SfxId`, which is an opaque u64 and
            // would make every identity unreadable in a diagnostic.
            //
            // A spec whose id does not resolve is already reported by
            // `validate()` above; minting an identity for it would invent a name
            // the registry does not actually authorize.
            if spec.sfx_id().is_err() {
                continue;
            }
            let name = match (&spec.id, spec.cue) {
                (Some(id), _) => id.clone(),
                (None, Some(cue)) => format!("{cue:?}"),
                (None, None) => continue,
            };
            out.define(facet.content_id_in(SFX_CUE_SCHEMA, name), canonical(spec));
        }

        if !out.failed() {
            out.lower(registry);
        }
    }
}

// ── lowered accessors — the runtime's load path ──────────────────────────────

pub fn lowered_music_registry(
    pack: &ambition_content_pack::PreparedContentPack,
) -> Option<&MusicRegistry> {
    pack.lowered::<MusicRegistry>(&SchemaId::new(MUSIC_REGISTRY_SCHEMA))
}

pub fn lowered_sfx_registry(
    pack: &ambition_content_pack::PreparedContentPack,
) -> Option<&SfxRegistry> {
    pack.lowered::<SfxRegistry>(&SchemaId::new(SFX_REGISTRY_SCHEMA))
}

// ── registrations ────────────────────────────────────────────────────────────

pub fn music_registry_schema() -> SchemaRegistration {
    SchemaRegistration {
        id: SchemaId::new(MUSIC_REGISTRY_SCHEMA),
        version: MUSIC_REGISTRY_VERSION,
        capability: CapabilityId::new(AUDIO_CAPABILITY),
        disposition: RuntimeDisposition::Runtime,
        doc: "Radio and room music: one pre-rendered track per row, plus the default. \
              Defines `music_track` identities and requires each track's audio file. GENERATED.",
        handler: Arc::new(MusicRegistrySchema),
    }
}

pub fn sfx_registry_schema() -> SchemaRegistration {
    SchemaRegistration {
        id: SchemaId::new(SFX_REGISTRY_SCHEMA),
        version: SFX_REGISTRY_VERSION,
        capability: CapabilityId::new(AUDIO_CAPABILITY),
        disposition: RuntimeDisposition::Runtime,
        doc: "Procedural sound-design cues: the synth sample rate and one waveform/envelope \
              spec per cue. Defines `sfx_cue` identities.",
        handler: Arc::new(SfxRegistrySchema),
    }
}

