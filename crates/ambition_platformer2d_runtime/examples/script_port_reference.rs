//! Print the author's reference to the ports a `.rhai` module may name
//! (`docs/sdk/script-ports.md`), generated from the ports' own descriptions:
//!
//!     cargo run -p ambition_platformer2d_runtime --features script_modules \
//!         --example script_port_reference > docs/sdk/script-ports.md
//!
//! `--json` prints the same as JSON, for a tool.

fn main() {
    let ports = ambition_platformer2d_runtime::extension_composition::script_ports();
    if std::env::args().any(|a| a == "--json") {
        println!("{}", ports.reference_json());
        return;
    }
    print!(
        "---\nstatus: current\n---\n\n\
         # Ports a script may name\n\n\
         Generated by `cargo run -p ambition_platformer2d_runtime --features script_modules \
         --example script_port_reference > docs/sdk/script-ports.md` from each port's own \
         description (`ambition_extension_sdk::structure`); edit the port, not this page.\n\n\
         A script reads its trigger as `this.trigger` and submits a request with\n\
         `this.requests.push(request(\"<alias>\", #{{ .. }}))`: `request` checks the value \
         against the port's description where it is called, so a misspelt field, a wrong kind \
         or a missing required field names the script's line. A field marked with a value under \
         \"when absent\" may be left out. Numbers are `f32`; a script may not write NaN or an \
         infinity. How a script is loaded: [iterating without a rebuild](../recipes/iterating-without-a-rebuild.md).\n\n\
         {}",
        ports.reference_markdown()
    );
}
