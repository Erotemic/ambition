//! The startup vanity card, DRAWN rather than played back.
//!
//! The authored card is nine rendered images plus a committed manifest
//! ([`crate::vanity_card`]), and the images are a git-ignored payload addressed
//! through an ipfs location. That is fine for a machine that has them and
//! nothing at all for one that does not — a fresh clone plays a card of
//! correctly-timed blank slots. This module draws the same beat out of ordinary
//! UI nodes, so the card is a property of the SOURCE and a checkout can always
//! play it.
//!
//! It is a shell SEGMENT, not a special case: the host registers
//! [`AMBITION_VANITY_CARD_SEGMENT_KIND`] as one card in the startup run-in, and
//! this module spawns its scene when that segment becomes current and reports
//! `ProgrammaticSegmentCompleted` when the beat is over. Skip, route
//! replacement, and failure all tear the scene down through
//! `ShellSegmentScopedEntity`, which the sequence plugin already owns — there is
//! no lifecycle here to get wrong.
//!
//! The joke is the robot's, and then it is the human's: *I MADE THIS* → the
//! handoff → *YOU MADE THIS?* → *I MADE THIS*. The timing is pinned to the
//! authored card's own total ([`crate::vanity_card::vanity_card_total_duration`])
//! so the two versions play at the same pace.

use std::time::Duration;

use ambition_platformer2d::game_shell::{
    ActiveShellSequence, FrontendOwnedEntity, FrontendPresentationKind, ShellActivationId,
    ShellSegmentId, ShellSegmentScopedEntity, ShellSequenceCommand,
};
use bevy::prelude::*;

/// Registered shell-segment kind for the programmatic replacement of the old
/// prerendered startup card.
pub const AMBITION_VANITY_CARD_SEGMENT_KIND: &str = "ambition_vanity_card";

/// The five beats, as RELATIVE weights rather than milliseconds.
///
/// ⚠ **they were five absolute constants and they were already wrong.** They
/// summed to 3900 ms against the authored card's 3902, so the equality this
/// module claims — that both versions tell the joke at the same pace — was
/// false the day it was written, by an amount no reviewer would ever spot. The
/// manifest is REGENERATED by an exporter, so any absolute copy of its length
/// drifts again on the next render.
///
/// Weights fix that by construction: the card is exactly as long as the authored
/// sequence, whatever that becomes, and only the SHAPE of the beat lives here.
const BEAT_WEIGHTS: Beats<u32> = Beats {
    intro: 700,
    handoff: 1000,
    question: 500,
    replay: 500,
    claim: 1200,
};

/// The card's five beats: the robot's claim, the handoff, the human's question,
/// a replayed glance, and the human's identical claim.
#[derive(Clone, Copy)]
struct Beats<T> {
    intro: T,
    handoff: T,
    question: T,
    replay: T,
    claim: T,
}

/// The beats in milliseconds, summing EXACTLY to the authored card's total.
///
/// The last beat takes the remainder rather than its own rounded share, so
/// integer division cannot leave the card a millisecond short of the segment
/// the host scheduled for it.
fn beats() -> Beats<Duration> {
    let total = crate::vanity_card::vanity_card_total_duration().as_millis() as u64;
    let weight_total = (BEAT_WEIGHTS.intro
        + BEAT_WEIGHTS.handoff
        + BEAT_WEIGHTS.question
        + BEAT_WEIGHTS.replay
        + BEAT_WEIGHTS.claim) as u64;
    let share = |weight: u32| total * weight as u64 / weight_total;

    let intro = share(BEAT_WEIGHTS.intro);
    let handoff = share(BEAT_WEIGHTS.handoff);
    let question = share(BEAT_WEIGHTS.question);
    let replay = share(BEAT_WEIGHTS.replay);
    Beats {
        intro: Duration::from_millis(intro),
        handoff: Duration::from_millis(handoff),
        question: Duration::from_millis(question),
        replay: Duration::from_millis(replay),
        claim: Duration::from_millis(total.saturating_sub(intro + handoff + question + replay)),
    }
}

/// How long the drawn card plays — the authored card's own total, so retiming
/// the manifest retimes this and there is nothing to keep in sync by hand.
pub fn programmatic_vanity_card_duration() -> Duration {
    crate::vanity_card::vanity_card_total_duration()
}

