fn animate_programmatic_vanity_card(
    time: Res<Time>,
    mut roots: Query<&mut VanityCardSceneRoot>,
    mut nodes: Query<&mut Node>,
    mut visibilities: Query<&mut Visibility>,
    mut backgrounds: Query<&mut BackgroundColor>,
    mut texts: Query<&mut Text>,
    mut commands: MessageWriter<ShellSequenceCommand>,
) {
    for mut root in &mut roots {
        root.elapsed = (root.elapsed + time.delta()).min(programmatic_vanity_card_duration());
        let state = sample_state(root.elapsed);

        if let Ok(mut bubble_node) = nodes.get_mut(root.bubble) {
            bubble_node.left = Val::Percent(state.bubble_left_pct);
            bubble_node.top = Val::Percent(7.0);
        }
        if let Ok(mut visibility) = visibilities.get_mut(root.bubble) {
            *visibility = if state.bubble_text.is_empty() {
                Visibility::Hidden
            } else {
                Visibility::Visible
            };
        }
        if let Ok(mut text) = texts.get_mut(root.bubble_text) {
            text.0 = state.bubble_text.to_string();
        }

        if let Ok(mut node) = nodes.get_mut(root.device) {
            node.left = Val::Percent(state.device_left_pct);
            node.top = Val::Percent(state.device_top_pct);
        }
        if let Ok(mut node) = nodes.get_mut(root.robot_arm) {
            node.width = Val::Px(state.robot_arm_width_px);
        }
        if let Ok(mut node) = nodes.get_mut(root.human_arm) {
            node.width = Val::Px(state.human_arm_width_px);
        }
        if let Ok(mut node) = nodes.get_mut(root.robot_card) {
            node.bottom = Val::Percent(state.robot_bottom_pct);
        }
        if let Ok(mut node) = nodes.get_mut(root.human_card) {
            node.bottom = Val::Percent(state.human_bottom_pct);
        }
        if let Ok(mut bg) = backgrounds.get_mut(root.robot_card) {
            *bg = BackgroundColor(if state.robot_emphasis {
                Color::srgb(0.80, 0.95, 1.0)
            } else {
                Color::srgb(0.73, 0.92, 0.98)
            });
        }
        if let Ok(mut bg) = backgrounds.get_mut(root.human_card) {
            *bg = BackgroundColor(if state.human_emphasis {
                Color::srgb(1.0, 0.92, 0.75)
            } else {
                Color::srgb(0.99, 0.86, 0.69)
            });
        }

        if !root.completion_sent && root.elapsed >= programmatic_vanity_card_duration() {
            commands.write(ShellSequenceCommand::ProgrammaticSegmentCompleted {
                activation_id: root.activation_id,
                segment_id: root.segment_id.clone(),
            });
            root.completion_sent = true;
        }
    }
}

#[derive(Clone, Copy)]
struct VanityCardSceneState {
    bubble_text: &'static str,
    bubble_left_pct: f32,
    device_left_pct: f32,
    device_top_pct: f32,
    robot_arm_width_px: f32,
    human_arm_width_px: f32,
    robot_bottom_pct: f32,
    human_bottom_pct: f32,
    robot_emphasis: bool,
    human_emphasis: bool,
}

fn sample_state(elapsed: Duration) -> VanityCardSceneState {
    let beats = beats();

    if elapsed < beats.intro {
        let mut pose = frame_pose(0);
        pose.bubble_text = "I MADE THIS";
        pose.bubble_left_pct = 8.0;
        pose.robot_emphasis = true;
        return pose;
    }

    let mut t = elapsed - beats.intro;
    if t < beats.handoff {
        let frame = ((t.as_secs_f32() / beats.handoff.as_secs_f32()) * 6.0)
            .floor()
            .clamp(0.0, 5.0) as usize;
        return frame_pose(frame);
    }

    t -= beats.handoff;
    if t < beats.question {
        let mut pose = frame_pose(5);
        pose.bubble_text = "YOU MADE THIS?";
        pose.bubble_left_pct = 58.0;
        pose.human_emphasis = true;
        return pose;
    }

    t -= beats.question;
    if t < beats.replay {
        // The glance back is the first half of the replay beat, whatever that
        // beat's length works out to — a fixed 250ms would silently become the
        // whole beat if the authored card ever got shorter.
        let frame = if t < beats.replay / 2 { 4 } else { 5 };
        return frame_pose(frame);
    }

    let mut pose = frame_pose(5);
    pose.bubble_text = "I MADE THIS";
    pose.bubble_left_pct = 60.0;
    pose.human_emphasis = true;
    pose.human_bottom_pct = 15.5;
    pose.device_top_pct = 55.5;
    pose
}

