#[cfg(test)]
mod tests {
    use super::*;

    /// ⚠ **this replaces a test that could not fail.** The ported version
    /// asserted `programmatic_vanity_card_duration() == vanity_card_total_duration()`,
    /// which is now the function's own body — green by construction, and it
    /// would stay green while the beats it schedules summed to something else
    /// entirely. THAT is the failure the original had: five absolute constants
    /// summing to 3900 ms against an authored 3902.
    ///
    /// So the property is the one integer division can actually break — the
    /// five beats reconstitute the whole card, leaving no unscheduled tail.
    #[test]
    fn the_beats_sum_to_the_whole_card_with_nothing_left_over() {
        let beats = beats();
        assert_eq!(
            beats.intro + beats.handoff + beats.question + beats.replay + beats.claim,
            programmatic_vanity_card_duration(),
            "the beats must reconstitute the card the host scheduled",
        );
    }

    #[test]
    fn opener_and_punchline_land_on_the_expected_speaker() {
        let intro = sample_state(Duration::from_millis(100));
        assert_eq!(intro.bubble_text, "I MADE THIS");
        assert!(intro.robot_emphasis);

        let end = sample_state(programmatic_vanity_card_duration());
        assert_eq!(end.bubble_text, "I MADE THIS");
        assert!(end.human_emphasis);
    }
}
