/// A ring the player lost, mid-scatter: it bursts from the body, arcs down,
/// bounces, is untouchable for a moment, is collectible for the rest of its
/// short life, and then is gone.
///
/// Rollback-registered, like `BallDash`. Position is not stored here: the
/// ring's `CenteredAabb` is the one position authority, so a magnet nudge and
/// this arc compose.
#[derive(bevy::prelude::Component, Clone, Copy, Debug)]
pub struct ScatteredRing {
    /// Current scatter velocity (screen frame, px/s).
    pub vel: ae::Vec2,
    /// Seconds left before the ring can be collected.
    pub lock: f32,
    /// Seconds left before the ring vanishes.
    pub life: f32,
}

/// Present a wallet-shield spend as a classic ring burst.
///
/// The shared victim resolver decides survival before HP or death. This
/// system consumes its fact and owns only Sanic's spawning, VFX, and SFX.
pub fn scatter_rings_on_hit(
    mut commands: bevy::prelude::Commands,
    active_session: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::lifecycle::ActiveSessionScope>,
    >,
    mut spent: bevy::prelude::MessageReader<ambition_platformer2d::damage::WalletShieldSpent>,
    mut vfx: ambition_platformer2d::vfx::VfxWriter,
    // The scatter is drawn in the live room of the struck body.
    rooms: ambition_platformer2d::platformer::lifecycle::LiveRooms,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
    mut bodies: bevy::prelude::Query<
        (
            &ambition_platformer2d::platformer::sim_id::SimId,
            &mut ambition_platformer2d::platformer::sim_id::SimIdCounter,
            // The window the resolver already armed, which this game lengthens.
            Option<&mut ambition_platformer2d::characters::actor::BodyCombat>,
        ),
        ambition_platformer2d::platformer::markers::PrimaryPlayerOnly,
    >,
) {
    let Some(scope) =
        ambition_platformer2d::platformer::lifecycle::SessionSpawnScope::for_optional_active_session(
            active_session.as_deref(),
        )
    else {
        return;
    };

    for event in spent.read() {
        let Ok((player_id, mut counter, combat)) = bodies.get_mut(event.victim) else {
            // Should be unreachable (`ensure_sim_id` stamps the primary player
            // early). Report it: otherwise the currency vanishes silently.
            bevy::log::error_once!(
                "wallet shield spent {} on {:?}, but the victim has no \
                 SimId/SimIdCounter to mint scattered rings from — the spend is \
                 invisible to the player",
                event.amount,
                event.victim
            );
            continue;
        };
        // Lengthen the invulnerability window: the hit throws the purse
        // across half a screen, and the resolver's default is over before the
        // rings land. `WalletShieldSpent` leaves the expression to content.
        // Raise, never replace: a longer running window (a hazard respawn
        // arms 1.10s) must not be cut short.
        let loss = crate::rules::sanic_rules().ring_loss;
        if let Some(mut combat) = combat {
            combat.damage_invuln_timer = combat.damage_invuln_timer.max(loss.invulnerable_seconds);
        }
        let scattered = (event.amount.max(0) as usize).min(loss.max_scattered);
        if scattered == 0 {
            continue;
        }
        // Rings leave in evenly-spaced shells around the full circle. The
        // half-slot offset keeps the spray symmetric about both axes and stops
        // any ring launching straight down into the floor it is standing on.
        let shell_size = loss.rings_per_shell.min(scattered);
        for i in 0..scattered {
            // Rings burst from the body in every direction and arc under
            // gravity.
            let shell = i / shell_size;
            let t = ((i % shell_size) as f32 + 0.5) / shell_size as f32;
            let angle = std::f32::consts::TAU * t;
            let speed = loss.burst_speed * loss.inner_shell_scale.powi(shell as i32);
            let vel = ae::Vec2::new(angle.cos(), angle.sin()) * speed;
            let size = ae::Vec2::splat(loss.ring_size);
            let seq = counter.next();
            let ring_id = ambition_platformer2d::platformer::sim_id::SimId::spawned(player_id, seq);
            let authored = ambition_platformer2d::world::rooms::Authored {
                id: ring_id.as_str().to_string(),
                name: "ring".to_string(),
                aabb: ae::Aabb::new(event.pos, size * 0.5),
                payload: {
                    let mut spec =
                        ambition_platformer2d::entity_catalog::placements::PickupSpec::new(
                            ambition_platformer2d::entity_catalog::PickupKind::Currency {
                                amount: 1,
                            },
                        );
                    spec.sprite = Some(RING_SPRITE_KIND.to_string());
                    spec
                },
            };
            let ring = ambition_platformer2d::item_runtime::construction::spawn_pickup(
                &mut commands,
                scope,
                &authored,
            );
            // No `SimIdCounter` by hand: `SimId` requires it, so a ring is born
            // able to be descended from like every other identified entity.
            commands.entity(ring).insert((
                ring_id.clone(),
                ambition_platformer2d::platformer::construction::SpawnOrigin::Dynamic {
                    parent: player_id.clone(),
                    sequence: seq,
                },
                ScatteredRing {
                    vel,
                    lock: loss.lock_seconds,
                    life: loss.life_seconds,
                },
                ambition_platformer2d::item_runtime::pickups::PickupCollectLock,
            ));
        }

        // At the rings' own launch speed, so the sparkle reads as the same
        // event and not a separate, smaller puff at the centre.
        vfx.for_room(rooms.of(event.victim))
            .write(crate::rules::sanic_rules().effects.ring_loss.at(event.pos, loss.burst_speed),
        );
        // H2: losing your rings is the struck body's cue.
        sfx.write_for(
            event.victim,
            ambition_platformer2d::sfx::SfxMessage::Play {
                id: ambition_platformer2d::sfx::SfxId::from_static(SFX_RING_LOSS),
                pos: event.pos,
            },
        );
    }
}

/// The whole life of a lost ring: burst, arc down, bounce, become
/// collectible, and expire.
///
/// Ordered `.after(magnetize_pickups).before(collect_ecs_pickups)`, so the
/// collector tests the ring at this frame's position. It adds to the ring's
/// `CenteredAabb` instead of owning it, so the magnet's pull and this arc
/// compose once the ring is collectible.
///
/// Deterministic: all state is the rollback-registered `ScatteredRing`, the
/// ring's AABB, the scaled sim dt, and static room geometry.
pub fn arc_scattered_rings(
    mut commands: bevy::prelude::Commands,
    time: bevy::prelude::Res<ambition_platformer2d::time::WorldTime>,
    // Each ring bounces off the walls of its own live room. A ring in no
    // live room has nothing to bounce off, and still falls and expires.
    world: ambition_platformer2d::platformer::lifecycle::LiveRoomOf<
        ambition_platformer2d::engine_core::RoomGeometry,
    >,
    mut rings: bevy::prelude::Query<(
        bevy::prelude::Entity,
        &mut ScatteredRing,
        &mut ae::CenteredAabb,
    )>,
) {
    let loss = crate::rules::sanic_rules().ring_loss;
    let dt = time.sim_dt();
    for (entity, mut ring, mut aabb) in &mut rings {
        let solids = world.of(entity).map(|geometry| &geometry.0);
        ring.life -= dt;
        if ring.life <= 0.0 {
            // Expired. Despawn instead of marking `Collected`: nobody took it.
            commands.entity(entity).despawn();
            continue;
        }
        ring.vel.y += loss.gravity * dt;
        ring.vel *= (1.0 - loss.air_drag * dt).max(0.0);
        let (moved, bounced) = ring_step(solids, aabb.aabb(), ring.vel * dt);
        aabb.center += moved;
        if let Some(normal) = bounced {
            // Reflect and damp, so the ring chatters where it fell and settles.
            ring.vel = (ring.vel - normal * (2.0 * ring.vel.dot(normal))) * loss.restitution;
        }
        if ring.lock > 0.0 {
            ring.lock -= dt;
            if ring.lock <= 0.0 {
                // Untouchable moment over: it is an ordinary currency pickup for
                // the rest of its life, on the shared collection path.
                commands
                    .entity(entity)
                    .remove::<ambition_platformer2d::item_runtime::pickups::PickupCollectLock>();
            }
        }
    }
}

/// Move a ring by `delta` against the room's geometry, stopping at the first
/// surface it meets: a hill, a loop or a slope as much as a solid block.
///
/// Returns the displacement actually taken and the contact normal, if any.
fn ring_step(
    world: Option<&ae::World>,
    ring: ae::Aabb,
    delta: ae::Vec2,
) -> (ae::Vec2, Option<ae::Vec2>) {
    let (Some(world), true) = (world, delta != ae::Vec2::ZERO) else {
        return (delta, None);
    };
    // A ring is round: sweep it as the ball it is drawn as, by the sweep a
    // rider flies with. Boxes alone let a spray fall through every hill.
    let radius = (ring.max.x - ring.min.x) * 0.5;
    let center = (ring.min + ring.max) * 0.5;
    match ae::movement::sweep_ball(world, center, radius, delta, ae::Vec2::Y) {
        Some(hit) => (delta * hit.toi.clamp(0.0, 1.0), Some(hit.normal)),
        None => (delta, None),
    }
}

