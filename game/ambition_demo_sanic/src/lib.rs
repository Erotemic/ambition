/// World x of the goal line.
///
/// Kept inside the player's reachable horizontal extent rather than at the
/// level's visual edge.
pub const GOAL_X: f32 = LEVEL_WIDTH - 400.0;

/// How long the results card holds before the act restarts.
pub const ACT_CLEAR_DWELL: f32 = 4.0;

/// Points per second of time left on a nominal par run, and the par itself.
/// A time bonus is what makes going FAST pay, which is the entire premise of
/// this demo — without it, a route that is safer but slower always wins.
///
/// Par is 30s against a measured ~6s clean run (see the act-completion proof),
/// so the bonus spreads meaningfully across real finishing times instead of
/// bunching every plausible run near the maximum.
pub const ACT_PAR_SECONDS: f32 = 30.0;
pub const TIME_BONUS_PER_SECOND: i32 = 100;
/// Each ring you finish holding is worth this.
///
/// Sized against the time bonus deliberately: a clean run banks roughly 2400
/// from time, and a full ring purse is worth roughly as much again. Two
/// currencies only pull against each other if they are of comparable size — at
/// the original 10/ring the time bonus swamped rings by an order of magnitude
/// and the "tension" this demo is built on did not exist in the arithmetic.
pub const RING_BONUS: i32 = 100;

/// The act's score, from the numbers captured at the clear.
pub fn act_score(time: f32, rings: i32) -> i32 {
    let remaining = (ACT_PAR_SECONDS - time).max(0.0);
    (remaining * TIME_BONUS_PER_SECOND as f32) as i32 + rings.max(0) * RING_BONUS
}

/// Format a duration the way a results screen does.
pub fn act_time_text(seconds: f32) -> String {
    let whole = seconds.max(0.0) as i32;
    format!("{}:{:02}", whole / 60, whole % 60)
}

/// Crossing the goal clears the act.
///
/// Captures the time and the rings AT THE CLEAR — the results card reads those,
/// not the live values, so picking a ring up during the outro cannot rewrite a
/// result the player is already looking at.
/// After the goal, the course drives him — not the player.
///
/// Measured, not guessed — with the late registration he decelerated and then crept forward at
/// a constant ~100 px/s forever, which is exactly what "held right, still accelerating" looks
/// like under a brake.
///
/// Found while proving the act-clear replay (room-replay triage §1): `GOAL_X` is
/// 400px from the right edge, and clearing neither braked him nor closed the
/// course, so he crossed the line at speed, ran out of level, and DIED inside
/// his own four-second results card. That also made `act_completion.rs`
/// structurally unable to assert the replay, because the death respawn rebuilt
/// the room by itself.
///
/// Zeroing the CONTROL rather than poking velocity matters here — he rides the surface-momentum
/// kernel, so a poked `vel` is overwritten from his surface parameter on the next tick, exactly
/// as a poked `pos` is.
fn take_the_controls_at_the_goal(
    subject: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::markers::ControlledSubject>,
    >,
    time: bevy::prelude::Res<ambition_platformer2d::time::WorldTime>,
    act: bevy::prelude::Query<&SanicActState>,
    mut commands: bevy::prelude::Commands,
    mut dashes: bevy::prelude::Query<&mut ball_dash::BallDash>,
    mut models: bevy::prelude::Query<&mut ambition_platformer2d::actor::MotionModel>,
    mut kinematics: bevy::prelude::Query<&mut ae::BodyKinematics>,
    mut holds: bevy::prelude::Query<&mut ambition_platformer2d::characters::control::ControlHolds>,
) {
    let cleared = act
        .iter()
        .any(|state| matches!(state.phase, SanicActPhase::Cleared { .. }));
    let Some(entity) = subject.and_then(|subject| subject.0) else {
        return;
    };
    if !cleared {
        // the act's OWN hold. Sanic can be held by something else at the same
        // time, and a brake that ended is not a reason to hand him back to a
        // system that is still driving him.
        ambition_platformer2d::characters::control::release_control_hold(
            &mut commands,
            entity,
            holds.get_mut(entity).ok().as_deref_mut(),
            ambition_platformer2d::characters::control::ControlHold::Sequence,
        );
        return;
    }
    // Clearing only locomotion was actively harmful: crouch is `locomotion.y`, so zeroing it looked
    // like a crouch RELEASE to `capture_ball_dash_input`, and a spin dash charged on the approach
    // fired itself the instant he crossed the line. The brake launched him.
    ambition_platformer2d::characters::control::claim_control_hold(
        &mut commands,
        entity,
        ambition_platformer2d::characters::control::ControlHold::Sequence,
    );
    // Blanking the frame stops him building any MORE charge, but a charge
    // already stored is spent on an edge, and the edge is exactly what the
    // blanking manufactures. Disarm it rather than trying to hide it.
    if let Ok(mut dash) = dashes.get_mut(entity) {
        dash.charge = 0.0;
        dash.crouched = false;
    }

    // Dropping the stick is not enough, and measuring is what showed it: at
    // finish-line speed his own friction covers the last 400px of course in well
    // under a second, so he still ran off the end. The authority for how fast he
    // is going is the momentum state's tangential speed `v_t` — NOT `vel`, which
    // is derived while riding — so the brake damps that. `vel` is damped too for
    // the airborne case, where it IS authoritative.
    let Ok(mut motion) = models.get_mut(entity) else {
        return;
    };
    // Sized by MEASUREMENT, not taste: exponential decay at rate k covers
    // roughly v/k px before stopping, and he crosses the line at ~1100 px/s with
    // 400px of course left. k=4 left him ~370px of coast, which put him over the
    // edge; k=9 stops him in ~120 and leaves real margin.
    const BRAKE_PER_SECOND: f32 = 9.0;
    let keep = (1.0 - BRAKE_PER_SECOND * time.sim_dt()).clamp(0.0, 1.0);
    if let ae::MotionModel::SurfaceMomentum(momentum) = &mut *motion {
        // A brake has no airborne answer — the kinematic velocity below is that
        // half — so the `false` return is deliberately ignored here.
        momentum.scale_tangential_speed(keep);
    }
    if let Ok(mut kin) = kinematics.get_mut(entity) {
        kin.vel.x *= keep;
    }
}

pub fn clear_act_at_goal(
    player: bevy::prelude::Query<
        (
            &ae::BodyKinematics,
            &ambition_platformer2d::characters::actor::BodyWallet,
        ),
        ambition_platformer2d::platformer::markers::PrimaryPlayerOnly,
    >,
    mut act: bevy::prelude::Query<&mut SanicActState>,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
    mut vfx: bevy::prelude::MessageWriter<ambition_platformer2d::vfx::VfxMessage>,
) {
    let Ok((kin, wallet)) = player.single() else {
        return;
    };
    for mut state in &mut act {
        if !matches!(state.phase, SanicActPhase::Running) || kin.pos.x < GOAL_X {
            continue;
        }
        state.phase = SanicActPhase::Cleared {
            time: state.elapsed,
            rings: wallet.balance,
            dwell: ACT_CLEAR_DWELL,
        };
        vfx.write(ambition_platformer2d::vfx::VfxMessage::Burst {
            pos: kin.pos,
            count: 40,
            speed: 320.0,
            color: [1.0, 0.92, 0.35, 1.0],
            kind: ambition_platformer2d::vfx::ParticleKind::Dust,
        });
        // H2/I3: the COURSE's. Clearing the act is the ACT's fanfare, belonging to
        // the course the way a goal jingle does — not to whoever happened to run
        // it, and not to whoever is hosting them.
        sfx.write_from(
            provider::SANIC_EXPERIENCE,
            ambition_platformer2d::sfx::SfxMessage::Play {
                id: ambition_platformer2d::sfx::SfxId::from_static(SFX_TRANSFORM),
                pos: kin.pos,
            },
        );
    }
}

/// The act restarts once the results have been read.
///
/// Same shape as Mary-O's cyclic level: the dwell is what makes the tally
/// legible before the world rebuilds under it, and the restart itself is the
/// engine's ordinary `RoomReplayRequested` rather than anything demo-specific.
pub fn cycle_act_after_clear(
    time: bevy::prelude::Res<ambition_platformer2d::time::WorldTime>,
    mut act: bevy::prelude::Query<&mut SanicActState>,
    mut replay: bevy::prelude::MessageWriter<
        ambition_platformer2d::actors::session::reset::RoomReplayRequested,
    >,
) {
    for mut state in &mut act {
        let SanicActPhase::Cleared { dwell, .. } = &mut state.phase else {
            continue;
        };
        *dwell -= time.scaled_dt;
        if *dwell > 0.0 {
            continue;
        }
        *state = SanicActState::default();
        replay.write(ambition_platformer2d::actors::session::reset::RoomReplayRequested);
    }
}

/// Value projections for this demo's rollback state.
///
/// Companion to Mary-O's `rollback_probes`, added in the same pass and for the same reason:
/// every one of these registrations was PRESENCE-ONLY, and the checker that says so had never
/// seen them.
///
/// f32 goes through `to_bits`. A rounding checksum calls two timelines equal
/// one ulp apart, and one ulp of a dash charge is one frame of launch speed.
mod rollback_probes {
    use super::*;

    pub(super) fn ball_dash(dash: &ball_dash::BallDash) -> u64 {
        (dash.charge.to_bits() as u64)
            ^ ((dash.crouched as u64) << 33)
            ^ ((dash.contact_grace.to_bits() as u64) << 1).rotate_left(11)
    }

    /// captured INPUT is rollback state, and its edges are the point. A
    /// rewind that restored the charge but not `crouch_released` re-runs the
    /// launch frame with the edge already consumed, so the two timelines
    /// disagree about whether the dash fired at all.
    pub(super) fn ball_dash_input(input: &ball_dash::BallDashInput) -> u64 {
        (input.crouch_held as u64)
            | ((input.crouch_released as u64) << 1)
            | ((input.rev_pressed as u64) << 2)
            | ((input.grounded_at_capture as u64) << 3)
    }

    pub(super) fn act_state(state: &SanicActState) -> u64 {
        let phase = match state.phase {
            SanicActPhase::Running => 1,
            SanicActPhase::Cleared { time, rings, dwell } => {
                2 ^ ((time.to_bits() as u64) << 8)
                    ^ ((rings as u32 as u64) << 24).rotate_left(5)
                    ^ ((dwell.to_bits() as u64) << 1).rotate_left(29)
            }
        };
        (state.elapsed.to_bits() as u64)
            ^ phase.rotate_left(17)
            ^ ((state.next_milestone as u64) << 48)
    }

    pub(super) fn super_form_latch(latch: &SuperFormLatch) -> u64 {
        latch.0 as u64
    }

    pub(super) fn scattered_ring(ring: &ScatteredRing) -> u64 {
        (ring.vel.x.to_bits() as u64)
            ^ ((ring.vel.y.to_bits() as u64) << 32)
            ^ ((ring.lock.to_bits() as u64) << 1).rotate_left(13)
            ^ ((ring.life.to_bits() as u64) << 1).rotate_left(41)
    }
}
