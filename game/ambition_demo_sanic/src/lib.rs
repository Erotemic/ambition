/// How many of the rings you were carrying actually scatter. The rest are gone.
///
/// Losing everything and being able to recover everything are both boring; the
/// classic answer is "you can get SOME of it back if you are quick", and the cap
/// is what keeps a big purse from turning a hit into a shower.
const SCATTERED_RINGS_MAX: usize = 12;

/// Outward launch speed (px/s) a scattered ring bursts from the body with.
///
/// The classic burst throws rings roughly four 16px pixels per frame; this world
/// runs at twice that tile scale, so the faithful conversion is ~480 px/s. It
/// wants to read as an EXPLOSION you have to chase, not a spill at your feet.
const SCATTER_BURST_SPEED: f32 = 900.0;

/// How many rings make up one shell of the burst. Past this, the next shell
/// launches slower, so a big purse bursts as an outer ring plus an inner one
/// instead of one over-dense circle.
const SCATTER_RINGS_PER_SHELL: usize = 6;

/// Speed multiplier for each shell inside the first — the classic halving,
/// softened slightly so the inner shell still clears the body.
const SCATTER_INNER_SHELL_SCALE: f32 = 0.55;

/// Downward pull (px/s²) that arcs a scattered ring back down, screen-relative
/// (the demo runs under normal screen gravity).
///
/// Paired with the launch speed, this is what SIZES the scatter: it pulls the
/// spray into an arc about three tiles high and a dozen wide — big enough to
/// read as an explosion and to make recovery a run, small enough that the rings
/// stay on the same screen you lost them on.
const SCATTER_GRAVITY: f32 = 1400.0;

/// Fraction of speed a loose ring sheds per second in the air.
///
/// Without it a ring launched horizontally never slows until it happens to clip
/// the floor, so the outermost pair of a burst simply leaves the level. Drag is
/// what BOUNDS the scatter: the rings still fly, but they land somewhere you
/// can get to.
const SCATTER_AIR_DRAG: f32 = 0.9;

/// Fraction of speed a scattered ring keeps when it bounces off geometry.
const SCATTER_RESTITUTION: f32 = 0.55;

/// How long (s) a scattered ring is untouchable. The ring is already bursting and bouncing during
/// this window; what it cannot do is be collected, so the hit costs you something even for the
/// instant you are standing in the spray.
///
/// classic is about two seconds of flashing, and the number has to be read against what the hit
/// COSTS here: the purse bursts across half a screen and the window is the whole of your chance to
/// run it back down.
///
/// it RAISES the running window, never replaces it. A hazard respawn arms
/// a longer one, and dropping rings inside that must not cut it short.
pub(crate) const RING_LOSS_INVULN_S: f32 = 2.0;

const SCATTER_LOCK_S: f32 = 0.6;

/// How long (s) a scattered ring exists at all. Past this it is gone, which is
/// what makes recovery a SCRAMBLE: the window is short enough that a big spray
/// is never fully recoverable, so a hit always costs something.
const SCATTER_LIFE_S: f32 = 4.2;

/// A ring the player LOST, mid-scatter (classic Sonic): it bursts from the body,
/// arcs down under gravity, bounces off whatever it lands on, spends a moment
/// untouchable, is collectible for the rest of its short life, and then is gone.
///
/// Rollback-registered sim state — the whole scatter has to resimulate
/// identically, so its velocity and both clocks ride the snapshot the same way
/// `BallDash` does. Position is NOT duplicated here: the ring's `CenteredAabb`
/// is the one position authority, so a magnet nudge and this system's arc
/// compose instead of one silently overwriting the other.
#[derive(bevy::prelude::Component, Clone, Copy, Debug)]
pub struct ScatteredRing {
    /// Current scatter velocity (screen frame, px/s).
    pub vel: ae::Vec2,
    /// Seconds left before the ring can be collected.
    pub lock: f32,
    /// Seconds left before the ring vanishes.
    pub life: f32,
}

/// Keep the generic wallet-backed shield aligned with the worn Sanic persona.
///
/// This is derived state, not an input edge: rebuilding it every frame avoids a
/// rollback latch while keeping the shared damage resolver content-agnostic.
///
/// It was inert only because
/// [`BodyWalletShield`](ambition_platformer2d::characters::actor::BodyWalletShield) has exactly one
/// writer in the workspace: this file.
///
/// [`sync_sanic_wallet_shield`] states that instead of relying on it: a body is
/// Sanic's business when it wears a Sanic persona (Sanic's rule speaks for
/// it) or already carries a shield — the second half is the giveback for a
/// body that stopped wearing Sanic, and it is a CLAIM (*nothing else grants
/// this*) rather than an accident. A George Booul on a Smash stage is neither,
/// and the loop skips him before it decides anything.
///
/// the residency test cannot be a query filter — `WornCharacter` holds an id
/// and Bevy filters on component presence — so it is the first statement in the
/// loop rather than part of this type.
type SanicShieldBodies<'w, 's> = bevy::prelude::Query<
    'w,
    's,
    (
        bevy::prelude::Entity,
        &'static ambition_platformer2d::characters::actor::WornCharacter,
        bevy::prelude::Has<ambition_platformer2d::characters::actor::BodyWalletShield>,
    ),
    ambition_platformer2d::platformer::markers::PrimaryPlayerOnly,
>;

/// Whether this character id is one of Sanic's forms.
fn is_sanic_persona(id: &str) -> bool {
    matches!(id, "sanic" | "super_sanic")
}

/// The one system that answers "does this body's wallet absorb a hit?"
///
/// The answer is *yes* for a Sanic persona standing in a Sanic room, and *no*
/// for everything this ruleset speaks for — which is a strictly smaller set than
/// "every body in the binary". `in_sanic_rooms` is read from the ACTIVE ROOM's
/// mode tag rather than from a constructor flag, so the hosted and standalone
/// compositions are one system: the speedway carries `mode: Some("sanic")`
/// whichever binary loads it, and the giveback that a hosted session needs on
/// the way out costs the standalone one nothing.
fn sync_sanic_wallet_shield(
    mut commands: bevy::prelude::Commands,
    active: Option<
        ambition_platformer2d::platformer::lifecycle::SessionWorldRef<
            ambition_platformer2d::world::rooms::ActiveRoomMetadata,
        >,
    >,
    bodies: SanicShieldBodies<'_, '_>,
) {
    let in_sanic_rooms = active.is_some_and(|active| active.0.mode.as_deref() == Some(SANIC_MODE));
    for (entity, worn, shielded) in &bodies {
        let sanic_persona = is_sanic_persona(worn.id());
        // not this ruleset's body. See `SanicShieldBodies`: Sanic answers
        // for the bodies wearing his personas, plus whatever already carries a
        // shield he is the only writer of. Everything else — every fighter on a
        // Smash stage this demo is composed beside — is somebody else's.
        if !sanic_persona && !shielded {
            continue;
        }
        let enabled = in_sanic_rooms && sanic_persona;
        match (enabled, shielded) {
            (true, false) => {
                commands
                    .entity(entity)
                    .try_insert(ambition_platformer2d::characters::actor::BodyWalletShield);
            }
            (false, true) => {
                commands
                    .entity(entity)
                    .remove::<ambition_platformer2d::characters::actor::BodyWalletShield>();
            }
            _ => {}
        }
    }
}

/// Present a wallet-shield spend as a classic ring burst.
///
/// Survival is already decided inside the shared victim resolver before HP or
/// death is evaluated. This system consumes the deterministic fact from that
/// resolver and owns only Sanic-specific entity spawning, VFX, and SFX.
pub fn scatter_rings_on_hit(
    mut commands: bevy::prelude::Commands,
    active_session: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::lifecycle::ActiveSessionScope>,
    >,
    mut spent: bevy::prelude::MessageReader<ambition_platformer2d::damage::WalletShieldSpent>,
    mut vfx: bevy::prelude::MessageWriter<ambition_platformer2d::vfx::VfxMessage>,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
    mut bodies: bevy::prelude::Query<
        (
            &ambition_platformer2d::platformer::sim_id::SimId,
            &mut ambition_platformer2d::platformer::sim_id::SimIdCounter,
            // The window the resolver already armed, which this game lengthens.
            Option<&mut ambition_platformer2d::characters::actor::BodyCombat>,
        ),
        ambition_platformer2d::platformer::markers::PrimaryPlayerOnly,
    >,
) {
    let Some(scope) =
        ambition_platformer2d::platformer::lifecycle::SessionSpawnScope::for_optional_active_session(
            active_session.as_deref(),
        )
    else {
        return;
    };

    for event in spent.read() {
        let Ok((player_id, mut counter, combat)) = bodies.get_mut(event.victim) else {
            // If the victim cannot be resolved here the currency is simply gone with no burst,
            // no sound, and no way to run it back down: a silent robbery. It should be
            // unreachable (`ensure_sim_id` stamps the primary player long before any hit
            // lands), so say so loudly rather than swallowing it.
            bevy::log::error_once!(
                "wallet shield spent {} on {:?}, but the victim has no \
                 SimId/SimIdCounter to mint scattered rings from — the spend is \
                 invisible to the player",
                event.amount,
                event.victim
            );
            continue;
        };
        // It is, for Ambition. Here the hit throws your purse across half a screen, so 0.75s is
        // over before the rings land and the badnik you bounced off is still touching you.
        //
        // `WalletShieldSpent`'s contract says where it belongs: "the generic resolver owns
        // survival; game content owns how it is expressed" — and in the classic, losing your rings
        // IS the trigger for the flashing window.
        //
        // raised, never replaced: a longer window already running (a hazard respawn arms 1.10s)
        // must not be cut short by dropping rings inside it.
        if let Some(mut combat) = combat {
            combat.damage_invuln_timer = combat.damage_invuln_timer.max(RING_LOSS_INVULN_S);
        }
        let scattered = (event.amount.max(0) as usize).min(SCATTERED_RINGS_MAX);
        if scattered == 0 {
            continue;
        }
        // Rings leave in evenly-spaced SHELLS around the full circle. The
        // half-slot offset keeps the spray symmetric about both axes and stops
        // any ring launching straight down into the floor it is standing on.
        let shell_size = SCATTER_RINGS_PER_SHELL.min(scattered);
        for i in 0..scattered {
            // Classic Sonic: the rings BURST from the body in every direction and
            // arc under gravity — an explosion you chase, not a fan you catch.
            let shell = i / shell_size;
            let t = ((i % shell_size) as f32 + 0.5) / shell_size as f32;
            let angle = std::f32::consts::TAU * t;
            let speed = SCATTER_BURST_SPEED * SCATTER_INNER_SHELL_SCALE.powi(shell as i32);
            let vel = ae::Vec2::new(angle.cos(), angle.sin()) * speed;
            let size = ae::Vec2::splat(18.0);
            let seq = counter.next();
            let ring_id = ambition_platformer2d::platformer::sim_id::SimId::spawned(player_id, seq);
            let authored = ambition_platformer2d::world::rooms::Authored {
                id: ring_id.as_str().to_string(),
                name: "ring".to_string(),
                aabb: ae::Aabb::new(event.pos, size * 0.5),
                payload: {
                    let mut spec =
                        ambition_platformer2d::entity_catalog::placements::PickupSpec::new(
                            ambition_platformer2d::entity_catalog::PickupKind::Currency {
                                amount: 1,
                            },
                        );
                    spec.sprite = Some(RING_SPRITE_KIND.to_string());
                    spec
                },
            };
            let ring = ambition_platformer2d::actors::features::ecs::spawn_static::spawn_pickup(
                &mut commands,
                scope,
                &authored,
            );
            // No `SimIdCounter` by hand: `SimId` requires it, so a ring is born
            // able to be descended from like every other identified entity.
            commands.entity(ring).insert((
                ring_id.clone(),
                ambition_platformer2d::platformer::construction::SpawnOrigin::Dynamic {
                    parent: player_id.clone(),
                    sequence: seq,
                },
                ScatteredRing {
                    vel,
                    lock: SCATTER_LOCK_S,
                    life: SCATTER_LIFE_S,
                },
                ambition_platformer2d::actors::features::PickupCollectLock,
            ));
        }

        vfx.write(ambition_platformer2d::vfx::VfxMessage::Burst {
            pos: event.pos,
            count: 24,
            // Matched to the rings' own launch speed, so the sparkle reads as the
            // same event and not a separate, smaller puff at the centre.
            speed: SCATTER_BURST_SPEED,
            color: [1.0, 0.86, 0.28, 1.0],
            kind: ambition_platformer2d::vfx::ParticleKind::Dust,
        });
        // H2: losing your rings is the struck BODY's cue.
        sfx.write_for(
            event.victim,
            ambition_platformer2d::sfx::SfxMessage::Play {
                id: ambition_platformer2d::sfx::SfxId::from_static(SFX_RING_LOSS),
                pos: event.pos,
            },
        );
    }
}

/// The whole life of a lost ring: burst outward, arc down, bounce off what
/// it lands on, become collectible, and expire.
///
/// Ordered `.after(magnetize_pickups).before(collect_ecs_pickups)`, so a ring is
/// already at this frame's position when the collector tests it, rather than
/// being credited at the spot it occupied on top of the knocked-back body. It
/// ADDS to the ring's `CenteredAabb` rather than owning it, so once the ring is
/// collectible the magnet's pull and this arc compose — the ring drifts toward a
/// nearby player while still falling, which is what makes a late grab feel
/// generous instead of impossible.
///
/// Deterministic: all state is the rollback-registered `ScatteredRing`, the
/// ring's own AABB, the scaled sim dt, and the room's static geometry — so it
/// resimulates identically.
pub fn arc_scattered_rings(
    mut commands: bevy::prelude::Commands,
    time: bevy::prelude::Res<ambition_platformer2d::time::WorldTime>,
    // Optional on purpose: `SessionWorldRef` is a `Single`, and a Single that
    // matches nothing SKIPS the system entirely — which would freeze every ring
    // in mid-air, forever, in any session without room geometry. Absent geometry
    // means "nothing to bounce off", not "stop simulating".
    world: Option<
        ambition_platformer2d::platformer::lifecycle::SessionWorldRef<
            ambition_platformer2d::engine_core::RoomGeometry,
        >,
    >,
    mut rings: bevy::prelude::Query<(
        bevy::prelude::Entity,
        &mut ScatteredRing,
        &mut ae::CenteredAabb,
    )>,
) {
    let dt = time.scaled_dt;
    let solids = world.as_deref().map(|geometry| &geometry.0);
    for (entity, mut ring, mut aabb) in &mut rings {
        ring.life -= dt;
        if ring.life <= 0.0 {
            // Time's up. Despawning (rather than marking `Collected`) is right:
            // nobody took this ring, so there is nothing to credit and no state
            // worth keeping — the ring simply stopped existing.
            commands.entity(entity).despawn();
            continue;
        }
        ring.vel.y += SCATTER_GRAVITY * dt;
        ring.vel *= (1.0 - SCATTER_AIR_DRAG * dt).max(0.0);
        let (moved, bounced) = ring_step(solids, aabb.aabb(), ring.vel * dt);
        aabb.center += moved;
        if let Some(normal) = bounced {
            // Reflect and damp. The classic read is a ring that chatters where
            // it fell, so it keeps a little over half its speed each contact and
            // settles quickly.
            ring.vel = (ring.vel - normal * (2.0 * ring.vel.dot(normal))) * SCATTER_RESTITUTION;
        }
        if ring.lock > 0.0 {
            ring.lock -= dt;
            if ring.lock <= 0.0 {
                // Untouchable moment over: it is an ordinary currency pickup for
                // the rest of its life, on the shared collection path.
                commands
                    .entity(entity)
                    .remove::<ambition_platformer2d::actors::features::PickupCollectLock>();
            }
        }
    }
}

/// Move a ring by `delta` against the room's solid geometry, stopping at the
/// first surface it meets.
///
/// Returns the displacement actually taken and the contact normal, if any.
fn ring_step(
    world: Option<&ae::World>,
    ring: ae::Aabb,
    delta: ae::Vec2,
) -> (ae::Vec2, Option<ae::Vec2>) {
    use ambition_platformer2d::engine_core::cast::SolidWorldQuery;
    let (Some(world), true) = (world, delta != ae::Vec2::ZERO) else {
        return (delta, None);
    };
    let mut nearest: Option<ambition_platformer2d::engine_core::geometry::AabbSweepHit> = None;
    // One-way platforms count only while the ring is FALLING — the same rule a
    // body gets. A ring should land on the platform you are standing on (that is
    // the point of a scatter you can run back through), but a ring thrown upward
    // must pass through its underside rather than bonk off it.
    let falling = delta.y > 0.0;
    world.for_each_solid_aabb(falling, &mut |solid| {
        if let Some(hit) = ae::AabbExt::sweep_hit(ring, delta, solid) {
            if nearest.is_none_or(|best| hit.time_of_impact < best.time_of_impact) {
                nearest = Some(hit);
            }
        }
    });
    match nearest {
        Some(hit) => (
            delta * hit.time_of_impact.clamp(0.0, 1.0),
            Some(hit.normal1),
        ),
        None => (delta, None),
    }
}

