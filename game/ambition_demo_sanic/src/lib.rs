/// Register Sanic's immutable authored definitions in one Bevy `App`: the
/// character fragment and the provider-indexed music/SFX fragments. Shared by the historical
/// [`SanicDemoContentPlugin`] (Startup-driven construction) and the new
/// [`provider::SanicExperiencePlugin`] (shell-activation-driven construction), so
/// there is one definition of Sanic's content seam.
///
/// The registered App-local resources are the sole composition authority.
/// Runtime simulation, presentation, dialogue, and combat consumers receive
/// the assembled catalog explicitly through Bevy resources.
pub fn install_sanic_content(app: &mut App) {
    use ambition_platformer2d::audio::catalog::{AudioCatalogAppExt, AudioCatalogFragment};
    use ambition_platformer2d::characters::actor::character_catalog::{
        CharacterCatalogAppExt, CharacterCatalogFragment,
    };

    app.register_character_catalog_fragment(
        CharacterCatalogFragment::from_ron(
            provider::SANIC_EXPERIENCE,
            Some(SANIC_CHARACTER_ID),
            SANIC_CATALOG_RON,
        )
        .expect("Sanic character catalog should be valid"),
    );
    // §7.6: both forms through the ONE character seam. Each registration publishes
    // the prepared definition and demands its art, so the standalone app stopped
    // naming sheets and stopped hand-rolling the decode.
    {
        use ambition_platformer2d::actors::character_runtime::CharacterDefinitionAppExt;
        use ambition_platformer2d::character::CharacterDefinition;
        // The sheet TARGET, not the sheet file: `sanic_spritesheet.ron` declares
        // `target: "sanic"`, and the registry is keyed by the target.
        // A VOICE, so neither stands mute on a Hall pedestal. A registered-only
        // character has no catalog row to hold bark pools, and the Hall's
        // ambient ticker skips anyone with nothing to say — so these two were
        // silent in the gallery while every catalog character chattered
        // . These are the FLOOR: a yarn node still wins.
        for (id, display, sheet, voice) in [
            (
                SANIC_CHARACTER_ID,
                "Sanic",
                "sanic",
                [
                    "You're too slow. No offense. Some offense.",
                    "I don't fight. I arrive, and then I've left.",
                    "Momentum is just a promise you keep to yourself.",
                ],
            ),
            (
                SUPER_SANIC_CHARACTER_ID,
                "Super Sanic",
                "super_sanic",
                [
                    "The rings were the tutorial. I am the exam.",
                    "Gravity had one job and it has been reassigned.",
                    "I went so fast I met the version of me that was leaving.",
                ],
            ),
        ] {
            // The ability is a real ceiling now
            // (`ambition_platformer2d::characters::action_scheme::combat_actions`), proved behaviourally by
            // `persona_architecture`'s
            // `the_demo_body_cannot_trigger_a_single_move_from_its_own_smash_table`.
            app.register_character(
                CharacterDefinition::new(id, display, provider::SANIC_EXPERIENCE)
                    .with_sheet(sheet)
                    .with_voice(voice)
                    .with_moveset(smash_moveset::sanic_moveset()),
            );
        }
    }
    // and the badnik itself, as a CHARACTER: its roster row is deleted and
    // its four placements name it.
    badnik::register_badnik_character(app);
    app.register_audio_catalog_fragment(
        AudioCatalogFragment::new(
            provider::SANIC_EXPERIENCE,
            Some(ambition_platformer2d::audio::spec::MusicRegistry {
                default_track: "you_are_too_slow".to_string(),
                tracks: vec![ambition_platformer2d::audio::spec::MusicTrack {
                    id: "you_are_too_slow".to_string(),
                    display_name: "You Are Too Slow".to_string(),
                    asset_path: Some(SANIC_MUSIC_ASSET_PATH.to_string()),
                    one_shot: false,
                }],
            }),
            // Sanic AUTHORS the cues it emits (Dash, Jump) rather than
            // inheriting them from the resident Ambition synth table. Declaring
            // them is what authorizes them under provider-relative SFX: a Sanic
            // session plays these and nothing else, and an Ambition-only bank id
            // resident in the shared bank cannot resolve here.
            Some(ambition_platformer2d::audio::spec::SfxRegistry {
                sample_rate: 44_100,
                sfx: sanic_sfx_specs(),
            }),
        )
        .expect("Sanic audio catalogs should be valid"),
    );
    // The animated ring sheet is CONTENT, not a property of one shell: register
    // it here so it loads identically whether Sanic runs standalone or as a mode
    // in the multi-game host (both add `SanicExperiencePlugin`, which calls this).
    // A prop is not carried in the lean sanic asset catalog, so this mirrors
    // Ambition's own intro-prop loader (a per-frame "insert if missing" GameAssets
    // mutation) rather than the catalog-fragment path — see smell #19.
    app.add_systems(bevy::prelude::Update, register_sanic_ring_prop_sheet);
    // The start-line legend names the buttons, so it belongs to the bindings and
    // not to the room file it is baked into. Registered with the CONTENT because
    // it is a fact about this room's signage, not about the rules.
    app.add_systems(bevy::prelude::Update, refresh_sanic_control_legend);

    // Sanic's mutable sim state joins the rollback contract through the same
    // seam engine crates use — here, before either construction path
    // fingerprints the App, so the schema fingerprint (part of the content
    // identity) includes these rows; a non-GGRS shell records metadata only.
    {
        use ambition_platformer2d::rollback::AmbitionRollbackApp;
        // `BallDash`/`BallDashInput` ride the player body, which `entity:body_kinematics`
        // already anchors.
        app.require_rollback::<SanicActState>("ambition_demo_sanic", "entity:sanic_mode_owner")
            .rollback_component_clone_probed::<ball_dash::BallDash>(
                "ambition_demo_sanic",
                "content.sanic_ball_dash",
                rollback_probes::ball_dash,
            )
            .rollback_component_clone_probed::<ball_dash::BallDashInput>(
                "ambition_demo_sanic",
                "content.sanic_ball_dash_input",
                rollback_probes::ball_dash_input,
            )
            .rollback_component_clone_probed::<SanicActState>(
                "ambition_demo_sanic",
                "content.sanic_act_state",
                rollback_probes::act_state,
            )
            .rollback_component_clone_probed::<SuperFormLatch>(
                "ambition_demo_sanic",
                "content.sanic_super_form_latch",
                rollback_probes::super_form_latch,
            )
            // A mid-burst scattered ring rides the currency pickup it decorates,
            // which `CenteredAabb`/`PickupFeature` already anchor + snapshot — so
            // like `BallDash` on the body, it only needs its own component
            // registered. Without this the burst would silently not resimulate.
            .rollback_component_clone_probed::<ScatteredRing>(
                "ambition_demo_sanic",
                "content.sanic_scattered_ring",
                rollback_probes::scattered_ring,
            )
            // Which monitors are spent is authoritative for the same reason
            // Mary-O's spent blocks and broken bricks are: the overlay subtracts
            // these from collision every frame, so a rewind across a break that
            // did not restore the set disagrees with the world about what is
            // still solid. Found by the shipped-composition resource sweep.
            .rollback_resource_clone_checksum::<monitors::SpentMonitors>(
                "ambition_demo_sanic",
                "content.sanic_spent_monitors",
                "bevy_ggrs clone snapshot + an order-independent checksum over the spent names",
                |spent| spent.checksum(),
            );
        // The dropped-ring id sequence is no longer a resource: each ring now
        // mints its identity from the SPAWNING player's own `SimIdCounter`
        // (rollback-registered per-entity state), so there is no global counter
        // to snapshot — and no cross-spawner coupling (ADR 0030).
    }
}

/// Ensure the animated `sanic_ring_prop` sheet lives in `GameAssets.props` so the
/// pickup renderer binds it (the ring's spinning sprite) instead of the static
/// coin. Insert-if-missing rather than a one-shot latch: it self-heals after the
/// host's wholesale `GameAssets` rebuild (the quality-scale reload wipes props),
/// and the insert flips `GameAssets::is_changed()` so the prop-rebind pass runs.
/// No-ops in a headless/sim-only build where no `GameAssets` (or renderer) exists.
fn register_sanic_ring_prop_sheet(
    game_assets: Option<
        bevy::prelude::ResMut<ambition_platformer2d::sprite_sheet::game_assets::GameAssets>,
    >,
    config: Option<
        bevy::prelude::Res<ambition_platformer2d::sprite_sheet::game_assets::GameAssetConfig>,
    >,
    asset_server: Option<bevy::prelude::Res<bevy::prelude::AssetServer>>,
    layouts: Option<
        bevy::prelude::ResMut<bevy::prelude::Assets<bevy::prelude::TextureAtlasLayout>>,
    >,
) {
    let (Some(mut game_assets), Some(config), Some(asset_server), Some(mut layouts)) =
        (game_assets, config, asset_server, layouts)
    else {
        return;
    };
    if config.no_assets || game_assets.characters.props.contains_key(RING_SPRITE_KIND) {
        return;
    }
    if let Some(asset) =
        ambition_platformer2d::actors::character_sprites::load_prop_sheet_for_target(
            &asset_server,
            &mut layouts,
            &config.sprite_folder,
            RING_SPRITE_KIND,
            &ambition_platformer2d::sprite_sheet::character::SheetTuning::new(1.0, 2),
        )
    {
        game_assets
            .characters
            .props
            .insert(RING_SPRITE_KIND.to_string(), asset);
    }
}

