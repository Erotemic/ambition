/// The act's live state, owned by the mode. It rides a `ModeScopedEntity`, so
/// leaving the Sanic rooms tears it down through the engine's lifetime-scope
/// vocabulary rather than a bespoke reset.
#[derive(bevy::prelude::Component, Clone, Copy, Debug, Default, PartialEq)]
pub struct SanicActState {
    /// Seconds the act has been running (sim clock, so bullet-time slows it).
    pub elapsed: f32,
    /// Running vs cleared. The clock stops on a clear, which is what turns the
    /// elapsed time from a stopwatch into a RESULT.
    pub phase: SanicActPhase,
    /// Next index in [`SPEED_MARKER_XS`] that should emit its one-shot progress
    /// cue. Mode-scoped with the act, so leaving and re-entering the demo resets
    /// the audible ruler without a global resource leak.
    pub next_milestone: usize,
}

/// Where the act is. `Cleared` carries the numbers the results card reads,
/// captured at the instant of the clear rather than re-derived afterwards —
/// otherwise the rings you pick up during the outro would keep changing your
/// result while you look at it.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub enum SanicActPhase {
    #[default]
    Running,
    Cleared {
        time: f32,
        rings: i32,
        /// Seconds the results card has left before the act restarts.
        dwell: f32,
    },
}

/// Sanic's level rules. ONE system list; a constructor flag decides its gating —
/// [`SanicRulesPlugin::hosted`] when Ambition hosts the demo alongside its own rooms,
/// [`SanicRulesPlugin::global`] when the demo IS the game.
pub struct SanicRulesPlugin {
    hosted: bool,
}

impl SanicRulesPlugin {
    /// Ambition hosts this demo: every rule sleeps outside the Sanic rooms.
    pub fn hosted() -> Self {
        Self { hosted: true }
    }

    /// The demo IS the game: the rules run unconditionally.
    pub fn global() -> Self {
        Self { hosted: false }
    }
}

impl Plugin for SanicRulesPlugin {
    fn build(&self, app: &mut App) {
        // The plugin OWNS its mandatory message channels and shared resources:
        // its systems write SFX cues, pop VFX bursts, read room-load facts, and
        // contribute to the collision overlay. A full app registers all of
        // these through the engine plugins; a thin rules-only harness may not,
        // and `add_message`/`init_resource` are idempotent.
        app.add_message::<ambition_platformer2d::sfx::OwnedSfxMessage>();
        app.add_message::<ambition_platformer2d::vfx::VfxMessage>();
        app.add_message::<ambition_platformer2d::damage::WalletShieldSpent>();
        app.add_message::<ambition_platformer2d::world::rooms::RoomLoaded>();
        // The act cycle restarts the room on a clear, exactly as Mary-O's level
        // cycle does. The engine registers this in a full app; a thin
        // rules-only harness may not, and `add_message` is idempotent.
        app.add_message::<ambition_platformer2d::actors::session::reset::RoomReplayRequested>();
        // SANIC'S DEATH RULES (ADR 0033). No interlude — losing a run in a
        // speed game is instant, and he has no death beat authored — and the act
        // goes back when nobody is left in play.
        //
        // stating this is not optional. The engine's default is `Never`, which is correct for a
        // versus stage and wrong for anything with a level: a pit that resets nothing leaves the
        // body falling out of the world forever.
        //
        // Standalone, the demo IS the game and its rules are the binary's, which is what lets a
        // rules-only harness use an untagged fixture room.
        {
            use ambition_platformer2d::combat::death_rules::DeathRulesAppExt as _;
            app.declare_death_rules(
                if self.hosted {
                    ambition_platformer2d::combat::death_rules::DeathRulesScope::Mode(SANIC_MODE)
                } else {
                    ambition_platformer2d::combat::death_rules::DeathRulesScope::EveryRoom
                },
                ambition_platformer2d::combat::death_rules::DeathRules::replay_level_after(0.0),
            );
        }
        app.init_resource::<ambition_platformer2d::world::FeatureEcsWorldOverlay>();
        use bevy::prelude::IntoScheduleConfigs;
        let sim = ambition_platformer2d::platformer::schedule::SimScheduleExt::sim_schedule(app);
        app.init_resource::<ball_dash::BallDashTuning>();
        // Sanic's half of a body reset, answered wherever a body is restarted —
        // a versus round boundary, a respawn, anything that says so. Registered
        // unconditionally and outside the mode gate on purpose: an observer that
        // only fires on `BodyRestarted` and only touches Sanic's own components
        // is inert for every other body, and gating it on the Sanic mode would
        // silently make the seam a no-op in exactly the crossover stage that
        // needs it.
        app.add_observer(ball_dash::clear_ball_dash_on_restart);
        // Utility is D in the classic preset, and the gate's clear is what now keeps that press
        // from ALSO toggling a host-code flight ability inherited by the control box — the demo
        // no longer arranges that itself.
        let sanic_pre_gate = (
            ball_dash::attach_ball_dash,
            declare_sanic_techniques,
            // Once cleared, the course drives him: the goal takes the stick away
            // and brakes him, so he cannot coast off the end and die inside his
            // own results card (room-replay triage §1).
            take_the_controls_at_the_goal,
        )
            .chain()
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::PlayerInput)
            .after(ambition_platformer2d::actors::avatar::ControlledBrainTick)
            .before(ambition_platformer2d::actors::avatar::WornControlGateSet);
        // AFTER the gate: read Sanic's rev and transformation from the sanctioned
        // technique edges the gate resolved — the fragile before-gate raw-verb
        // interception windows are GONE (neither a plain melee edge nor a raw
        // Utility edge is the API any more).
        //  IN `WorldPrep`, WHICH IS WHERE THE GATE IS. The gate used to sit in
        // `PlayerInput`, and it moved because a restriction over control has to
        // run after BOTH publications and an autonomous body's lands in
        // `WorldPrep` (D202). "After the gate" is the real requirement here, so
        // the phase follows it — pinning `PlayerInput` beside it is what turned
        // the move into a schedule CYCLE rather than a relocation.
        let sanic_post_gate = (
            ball_dash::capture_ball_dash_input,
            toggle_sanic_form,
        )
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::WorldPrep)
            .after(ambition_platformer2d::actors::avatar::WornControlGateSet);
        if self.hosted {
            app.add_systems(
                sim,
                sanic_pre_gate.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                sanic_post_gate.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
        } else {
            app.add_systems(sim, sanic_pre_gate);
            app.add_systems(sim, sanic_post_gate);
        }
        // The marker is identity- AND room-derived: leaving the Sanic rooms
        // removes the shield even if the same worn persona remains selected
        // elsewhere, where no ring-scatter consumer is awake.
        //
        // The fork's only real content was "does the host have other rooms to leave", which is a
        // question about the ROOM, and the room already answers it.
        app.add_systems(
            sim,
            sync_sanic_wallet_shield
                .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::PlayerInput)
                // A provider ordering against `apply_worn_character_gameplay` is coupled to a
                // name the engine may rename or split; `Persona` is the contract.
                .after(ambition_platformer2d::platformer::schedule::PlayerInputSet::Persona)
                .before(ambition_platformer2d::damage::PlayerHitResolutionSet),
        );

        // The ball dash is a RULE, not world content: it exists while the Sanic
        // mode is live and nowhere else, exactly like the act clock. Effects run
        // after PlayerInput captured the technique and before later presentation.
        // `tick_ball_dash` precedes `tick_rolling`, so a launch cannot un-ball in
        // the same frame even if tuning changes.
        let rules = (
            spawn_sanic_mode_owner,
            tick_sanic_act,
            ball_dash::tick_ball_dash,
            ball_dash::tick_rolling,
            // Project the roll authority (`Rolling`) onto the anim fact AFTER
            // both the launch (insert) and the stand-up (remove) have settled,
            // so the looping `ball` row tracks the physical ball for the frame.
            ball_dash::mirror_ball_anim_fact,
            // His transformation numbers ride his body, so the engine beat
            // reads authored feel rather than a default.
            ensure_sanic_transform_beat_policy,
            // The super form's derived traits (invincibility + sparkles) track
            // the worn identity every frame — toggle- and monitor-agnostic.
            sync_super_form_traits,
            // Braking scrape on the skid onset (reads the published skid fact).
            emit_sanic_skid_sfx,
            // The goal, then the cycle: a clear captured this frame must be
            // read by the card before the dwell can retire it.
            clear_act_at_goal,
            cycle_act_after_clear,
        )
            .chain()
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::GameplayEffects);
        // The super form states its TRAITS before the engine runs them.
        //
        // an ORDER, not an installation. `apply_contact_harm` is still
        // deliberately absent from this game: `defeat_badniks` already owns the
        // destroy-on-touch reaction, including its pop and its bounce, and two
        // authorities killing the same badnik is what that choice exists to
        // stop. The engine owning EXPIRY takes nothing away from it.
        app.configure_sets(
            sim,
            ambition_platformer2d::actors::features::empowerment::EmpowermentExpiry
                .after(sync_super_form_traits)
                .before(emit_sanic_skid_sfx),
        );
        let milestone_sfx = emit_sanic_milestone_sfx
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::GameplayEffects);
        // The badnik defeat runs BEFORE the engine's shared body-contact-damage
        // pass so a stomp/roll never also hurts Sanic (the rule zeroes the
        // badnik's health that frame; the contact pass skips a dead attacker).
        let badniks = (
            // Declare dormancy before anything ticks a brain: a badnik at the far
            // end of the speedway should not be walking off a ledge while Sanic
            // is still at the start. Mirrors Mary-O's per-character declaration,
            // and the radius is derived from Sanic's own top speed rather than
            // copied from hers (see `BADNIK_WAKE_RADIUS`).
            badnik::tag_sanic_badniks,
            badnik::defeat_badniks,
        )
            .chain()
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::WorldPrep)
            .before(ambition_platformer2d::platformer::schedule::WorldPrepSet::ContactDamage);
        // The shared player resolver spends wallet armor before death and emits
        // the deterministic fact this Sanic presentation consumes.
        let ring_loss = scatter_rings_on_hit
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::PlayerSimulation)
            .after(ambition_platformer2d::damage::PlayerHitResolutionSet);
        // The scattered-ring burst flies out BETWEEN the coin magnet and the
        // collect: it owns each ring's position during the lock so the magnet
        // can't reclaim it, and collect then sees the ring out at its arc rather
        // than on top of the knocked-back body.
        let scatter_arc = arc_scattered_rings
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::FeatureCollection)
            .after(ambition_platformer2d::actors::features::PickupMagnetize)
            .before(ambition_platformer2d::actors::features::PickupCollect);
        // Monitor boxes: re-arm on (re)load, break on stomp/roll, tick the
        // speed-shoes grant. Broken monitors contribute to the overlay's
        // `removed_block_names` AFTER the engine's per-frame rebuild clears it
        // (the same slot Mary-O's bricks and encounter lock walls take).
        app.init_resource::<monitors::SpentMonitors>();
        let monitor_rules = (
            monitors::rearm_monitors_on_room_loaded,
            monitors::break_monitor_boxes,
            monitors::tick_speed_shoes,
        )
            .chain()
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::GameplayEffects);
        let monitor_overlay = monitors::contribute_broken_monitors_to_overlay
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::WorldPrep)
            .after(ambition_platformer2d::actors::features::FeatureWorldOverlaySet);
        if self.hosted {
            app.add_systems(
                sim,
                rules.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                milestone_sfx.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                badniks.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                ring_loss.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                scatter_arc.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                monitor_rules.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                monitor_overlay.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
        } else {
            app.add_systems(sim, rules);
            app.add_systems(sim, milestone_sfx);
            app.add_systems(sim, badniks);
            app.add_systems(sim, ring_loss);
            app.add_systems(sim, scatter_arc);
            app.add_systems(sim, monitor_rules);
            app.add_systems(sim, monitor_overlay);
        }
    }
}

/// Play the braking scrape on the frame the controlled body STARTS skidding.
///
/// `BodyMotionFacts::skidding` is published every step by the momentum
/// integration (steer-against-fast-travel while riding); a rising edge fires the
/// scrape once per skid onset instead of every tick it holds. One controlled body
/// plays it, so a `Local` edge latch is sufficient.
fn emit_sanic_skid_sfx(
    subject: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::markers::ControlledSubject>,
    >,
    mut was_skidding: bevy::prelude::Local<bool>,
    bodies: bevy::prelude::Query<(&ae::BodyMotionFacts, &ae::BodyKinematics)>,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
) {
    let subject = subject.and_then(|s| s.0);
    let skid = subject.and_then(|e| bodies.get(e).ok());
    let (skidding, pos) = skid.map_or((false, ae::Vec2::ZERO), |(facts, kin)| {
        (facts.skidding, kin.pos)
    });
    if skidding && !*was_skidding {
        // H2: the scrape is the SKIDDING BODY's, not the session owner's. In a
        // Sanic-only game those agree; in a crossover they do not, and Sanic's
        // most recognisable sound would come out of the host's bank.
        if let Some(subject) = subject {
            sfx.write_for(
                subject,
                ambition_platformer2d::sfx::SfxMessage::Play {
                    id: ambition_platformer2d::sfx::SfxId::from_static(SFX_SKID),
                    pos,
                },
            );
        }
    }
    *was_skidding = skidding;
}

/// The id Sanic's form toggle carries in the action scheme, and therefore the
/// word on the control that fires it: `ActionSpec::display` title-cases the id,
/// so this reads "Transform" — the demo's own vocabulary for the mechanic
/// ([`SFX_TRANSFORM`], the transform beat, the super row's `"transformation"`
/// tag). No `display_name` override, so the label cannot drift from the id.
const TRANSFORM_TECHNIQUE_ID: &str = "transform";

/// Sanic's technique declarations — what the body's bespoke mechanics are CALLED
/// and which control each lives on. ONE writer for the whole set, upserting by
/// slot, so no two Sanic systems race to own `ActorTechniques`.
fn declare_sanic_techniques(
    mut commands: bevy::prelude::Commands,
    subject: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::markers::ControlledSubject>,
    >,
    mut bodies: bevy::prelude::Query<
        Option<&mut ambition_platformer2d::characters::action_scheme::ActorTechniques>,
        bevy::prelude::With<ae::BodyKinematics>,
    >,
) {
    use ambition_platformer2d::entity_catalog::action_scheme as sch;

    let Some(entity) = subject.and_then(|subject| subject.0) else {
        return;
    };
    let Ok(techniques) = bodies.get_mut(entity) else {
        return;
    };
    let declared = [ball_dash::spin_dash_technique(), transform_technique()];
    match techniques {
        Some(mut techniques) => {
            // Already correct in steady state: writing anyway would tick change
            // detection every frame and re-derive the scheme for nothing.
            let current: Vec<&sch::ActionSpec> = declared
                .iter()
                .filter_map(|spec| techniques.0.iter().find(|a| a.slot == spec.slot))
                .collect();
            if current.len() == declared.len()
                && current.iter().zip(declared.iter()).all(|(a, b)| *a == b)
            {
                return;
            }
            for spec in declared {
                techniques.0.retain(|a| a.slot != spec.slot);
                techniques.0.push(spec);
            }
        }
        None => {
            commands.entity(entity).try_insert(
                ambition_platformer2d::characters::action_scheme::ActorTechniques(
                    declared.to_vec(),
                ),
            );
        }
    }
}

/// The transformation's identity in the action scheme: a technique on the
/// mode-switch slot, which is where its input already lived.
fn transform_technique() -> ambition_platformer2d::entity_catalog::action_scheme::ActionSpec {
    use ambition_platformer2d::entity_catalog::action_scheme as sch;
    sch::ActionSpec {
        id: sch::ActionId::new(TRANSFORM_TECHNIQUE_ID),
        slot: sch::ControlSlot::Utility,
        display_name: None,
        visual: None,
        gate: sch::ActionGate::Technique(TRANSFORM_TECHNIQUE_ID.to_string()),
    }
}

/// Toggle the controlled body between the two catalog-authored Sanic forms.
///
/// Because the body DECLARES `transform` there, the gate routes the press here and clears the
/// raw verb itself, so the old hand-rolled consumption (and the ordering it depended on) is the
/// engine's job now.
///
/// The super row authors the form's boosted movement and `sync_super_form_traits`
/// derives the rest (invincibility, sparkles, badnik destroy-on-touch) from the
/// worn identity every frame — so this toggle grants and revokes the FULL form,
/// and `WornCharacter` stays the single gameplay + presentation authority. No
/// timer: a future ring drain can wear the form off the same way this toggle does.
///
/// and it sheds the speed shoes, because a wear REPLACES the live `MomentumParams` wholesale: a
/// shoes grant that outlives the swap would later "restore" a baseline saved from the other form's
/// authored row.
fn toggle_sanic_form(
    mut commands: bevy::prelude::Commands,
    subject: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::markers::ControlledSubject>,
    >,
    mut bodies: bevy::prelude::Query<(
        &ambition_platformer2d::characters::action_scheme::ResolvedTechniqueEdges,
        &mut ambition_platformer2d::characters::actor::WornCharacter,
    )>,
) {
    let Some(entity) = subject.and_then(|subject| subject.0) else {
        return;
    };
    let Ok((edges, mut worn)) = bodies.get_mut(entity) else {
        return;
    };
    if !edges.pressed(TRANSFORM_TECHNIQUE_ID) {
        return;
    }

    let next = match worn.id() {
        SANIC_CHARACTER_ID => SUPER_SANIC_CHARACTER_ID,
        SUPER_SANIC_CHARACTER_ID => SANIC_CHARACTER_ID,
        _ => return,
    };
    // The transform SOUND fires from the worn-identity edge in
    // `sync_super_form_traits`, so wearing the form is all this does — plus
    // dropping any live shoes, whose saved baseline belongs to the form being
    // taken off.
    *worn = ambition_platformer2d::characters::actor::WornCharacter::new(next);
    commands.entity(entity).remove::<monitors::SpeedShoes>();
}

/// How often the super form's sparkle trail pulses (sim seconds).
const SUPER_SPARKLE_PERIOD: f32 = 0.14;
/// Radius of the sparkle orbit around the body centre (px).
const SUPER_SPARKLE_RADIUS: f32 = 15.0;
/// Upward bias of the sparkle ring (px, toward the torso) so the falling motes
/// hover AROUND the body rather than pooling at the feet.
const SUPER_SPARKLE_RISE: f32 = 8.0;

/// Sanic's transformation beat is shorter and lighter than Mary-O's so it does not interrupt
/// the speed-focused demo.
fn ensure_sanic_transform_beat_policy(
    mut commands: bevy::prelude::Commands,
    bodies: bevy::prelude::Query<
        bevy::prelude::Entity,
        (
            bevy::prelude::With<ambition_platformer2d::platformer::markers::PrimaryPlayer>,
            bevy::prelude::Without<
                ambition_platformer2d::actors::features::transform_beat::TransformBeatPolicy,
            >,
        ),
    >,
) {
    for entity in &bodies {
        commands.entity(entity).try_insert(
            ambition_platformer2d::actors::features::transform_beat::TransformBeatPolicy {
                duration: 0.35,
                anim: ambition_platformer2d::sprite_sheet::character::CharacterAnim::Taunt,
                clock_scale: 0.5,
                untouchable: true,
            },
        );
    }
}

/// Derive super-form traits from the worn identity each simulation frame.
///
/// Movement speed is authored on the `super_sanic` catalog row. This system adds invulnerability
/// to contact and spike-strip damage plus the golden sparkle trail. Pits still reset the body
/// through `ResetCause::LeftTheWorld`. The derived traits revert when the super identity is removed.
fn sync_super_form_traits(
    time: bevy::prelude::Res<ambition_platformer2d::time::WorldTime>,
    mut sparkle_accum: bevy::prelude::Local<f32>,
    mut sparkle_orbit: bevy::prelude::Local<f32>,
    mut vfx: bevy::prelude::MessageWriter<ambition_platformer2d::vfx::VfxMessage>,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
    mut commands: bevy::prelude::Commands,
    mut players: bevy::prelude::Query<
        (
            bevy::prelude::Entity,
            &ambition_platformer2d::characters::actor::WornCharacter,
            &ae::BodyKinematics,
            Option<&SuperFormLatch>,
        ),
        bevy::prelude::With<ambition_platformer2d::platformer::markers::PrimaryPlayer>,
    >,
) {
    // `None` = no controlled player (the session has retired; a player is present
    // for every in-session frame, surviving room changes). Derive invincibility
    // and capture the emit position while the body is borrowed.
    let (worn_is_super, pos, body, was_super) = match players.single_mut() {
        Ok((body, worn, kinematics, latch)) => {
            let is_super = worn.id() == SUPER_SANIC_CHARACTER_ID;
            // Super Sanic and Mary-O's pocket quasar are the SAME fact wearing two names: a body
            // that cannot be hurt, and that destroys what it runs through, because a star-grade
            // power is on.
            //
            // HELD, not timed: the form is true for exactly as long as he wears
            // the identity, and the identity is the authority — a monitor, the
            // D-toggle, or a future ring drain all wear it off, and none of them
            // has to know a timer exists.
            if is_super {
                commands.entity(body).try_insert(
                    ambition_platformer2d::actors::features::empowerment::Empowered::held(
                        SUPER_SANIC_SUPER_STATE,
                    ),
                );
            } else {
                commands
                    .entity(body)
                    .remove::<ambition_platformer2d::actors::features::empowerment::Empowered>();
            }
            (
                Some(is_super),
                kinematics.pos,
                Some(body),
                latch.is_some_and(|latch| latch.0),
            )
        }
        Err(_) => (None, ae::Vec2::ZERO, None, false),
    };

    // The transform SOUND derives from the worn-identity EDGE, so it fires once no
    // matter what wore the form (the D-toggle, a monitor, a future ring drain). The
    // edge is resolved session-turnover-safe: no controlled player resolves to
    // `false` so the edge state never leaks into the next session — otherwise a
    // session that ended super would fire a phantom detransform on the next
    // session's first frame. The latch rides the BODY now, so a retired session
    // takes it with the body rather than needing teardown to reach it.
    let (cue, next_super) = super_form_edge(worn_is_super, was_super);
    if let Some(body) = body {
        commands.entity(body).try_insert(SuperFormLatch(next_super));
    }
    if let Some(to_super) = cue {
        // H2: a transformation is the most character-defining sound a body makes.
        // Attributed to the transforming body, falling back to the session only
        // when nothing published a source for it.
        let transform = ambition_platformer2d::sfx::SfxMessage::Play {
            id: ambition_platformer2d::sfx::SfxId::from_static(if to_super {
                SFX_TRANSFORM
            } else {
                SFX_DETRANSFORM
            }),
            pos,
        };
        match body {
            // I3: with no body to attribute it to, the fallback is the COURSE that
            // authored the cue — not the session, which under a shell host is the
            // launcher and has never heard of this sound.
            Some(body) => sfx.write_for(body, transform),
            None => sfx.write_from(provider::SANIC_EXPERIENCE, transform),
        }
        // Becoming super only: dropping the form is a loss, and a loss does not get a celebratory
        // beat. The engine owns what the beat does; this only says it happened.
        if to_super {
            if let Some(body) = body {
                commands.entity(body).try_insert(
                    ambition_platformer2d::actors::features::transform_beat::TransformBeatRequested,
                );
            }
        }
    }

    // Sparkles only while a super body is present; otherwise the accumulator + orbit
    // reset, so two consecutive super sessions start with identical sparkle phase.
    if worn_is_super != Some(true) {
        *sparkle_accum = 0.0;
        *sparkle_orbit = 0.0;
        return;
    }
    *sparkle_accum += time.scaled_dt;
    if *sparkle_accum >= SUPER_SPARKLE_PERIOD {
        *sparkle_accum -= SUPER_SPARKLE_PERIOD;
        // Orbit the emit point AROUND the body so the motes read as a golden
        // aura ring, not a stream out of one point (Shard's heavy gravity turned
        // a centre-emit burst into a dribble). The golden-angle step spreads
        // successive pulses evenly around the ring; the upward bias keeps the
        // (still-falling) Spark motes hovering around the torso.
        *sparkle_orbit += 2.399_963; // golden angle, radians
        let ring = ae::Vec2::new(sparkle_orbit.cos(), sparkle_orbit.sin()) * SUPER_SPARKLE_RADIUS;
        vfx.write(ambition_platformer2d::vfx::VfxMessage::Burst {
            pos: pos + ring - ae::Vec2::new(0.0, SUPER_SPARKLE_RISE),
            count: 2,
            speed: 26.0,
            color: [1.0, 0.9, 0.4, 1.0],
            kind: ambition_platformer2d::vfx::ParticleKind::Spark,
        });
    }
}

/// Whether this body wore the super form last frame.
///
/// Rollback state rather than a `Local<bool>`: the edge it feeds decides whether
/// a transformation beat happens, and a latch the rewind cannot see makes that
/// decision unreproducible — resimulating a rewound frame would re-fire a beat
/// that already played, or skip one that had not. It rides the body so it is
/// restored, despawned, and re-derived with the body it describes.
#[derive(bevy::prelude::Component, Clone, Copy, Debug, Default, PartialEq)]
pub struct SuperFormLatch(pub bool);

/// The super-form transform-cue edge, resolved so session-local latch state never
/// leaks across a session turnover.
///
/// `worn_is_super` is `None` when no player is controlled (the session has
/// retired). Returns `(cue, next_latch)`: a `Some(true)` cue is a transform, a
/// `Some(false)` a detransform, `None` no cue. With no controlled player the latch
/// RESETS to `false` and no cue fires, so a session that ended super cannot make
/// the next session emit a phantom detransform on its first frame.
fn super_form_edge(worn_is_super: Option<bool>, was_super: bool) -> (Option<bool>, bool) {
    match worn_is_super {
        None => (None, false),
        Some(is_super) if is_super != was_super => (Some(is_super), is_super),
        Some(_) => (None, was_super),
    }
}

/// Bring the act state into being the first frame the mode is live. Spawned
/// `spawn_mode_scoped`, so the engine despawns it when the active room's mode
/// changes — no teardown code here.
fn spawn_sanic_mode_owner(
    mut commands: bevy::prelude::Commands,
    existing: bevy::prelude::Query<(), bevy::prelude::With<SanicActState>>,
    session: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::lifecycle::ActiveSessionScope>,
    >,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
) {
    use ambition_platformer2d::platformer::lifecycle::{SessionSpawnScope, SpawnSessionScopedExt};
    // Sleep when a session-scoped host has retired the live session (i.e. at the
    // launcher): the room metadata may still read "sanic" until the next
    // activation overwrites it, but there is no session to own new state, so the
    // act owner must not be resurrected. When no `ActiveSessionScope` exists at
    // all (the historical Startup path and the D-C tests) the guard is inert.
    let session_live = session
        .as_ref()
        .map_or(true, |scope| scope.current().is_some());
    let spawn_scope = session
        .as_ref()
        .map_or(SessionSpawnScope::UNSCOPED, |scope| scope.spawn_scope());
    if session_live && existing.iter().next().is_none() {
        // Owned by BOTH the mode (survives in-session room changes) and the
        // active session (torn down on a shell relaunch, which a same-mode
        // reload is NOT — so mode-scope alone would leak the act across a
        // launch → quit → relaunch cycle).
        commands
            .spawn_session_scoped(spawn_scope, SanicActState::default())
            .insert(
                ambition_platformer2d::platformer::lifecycle::ModeScopedEntity(
                    SANIC_MODE.to_string(),
                ),
            );
        // Audible confirmation that the standalone shell is draining the
        // standard SfxMessage seam. Distance markers emit alternating cues as
        // the player advances, so this one also proves the bank at room entry.
        //
        // H2/I3: the COURSE's, by name. The room announces that the runner passed
        // it, so it is neither the runner's sound nor the host's — and
        // `write_global` would have made it the host's, because it reaches for the
        // session context.
        sfx.write_from(
            provider::SANIC_EXPERIENCE,
            ambition_platformer2d::sfx::SfxMessage::Dash {
                pos: ae::Vec2::ZERO,
            },
        );
    }
}

/// The act timer runs on the SIM clock (`scaled_dt`), so bullet-time and pause
/// slow it exactly as they slow everything else — `WorldTime`, never `Res<Time>`.
fn tick_sanic_act(
    time: bevy::prelude::Res<ambition_platformer2d::time::WorldTime>,
    mut act: bevy::prelude::Query<&mut SanicActState>,
) {
    for mut state in &mut act {
        if matches!(state.phase, SanicActPhase::Running) {
            state.elapsed += time.scaled_dt;
        }
    }
}

/// Emit a small, existing Ambition cue when the primary body crosses each
/// visible distance marker. These are deliberately simple diagnostic sounds:
/// the demo is proving that its shell drains the standard [`ambition_platformer2d::sfx::SfxMessage`] seam,
/// not inventing a parallel Sanic audio stack.
fn emit_sanic_milestone_sfx(
    player: bevy::prelude::Query<
        &ae::BodyKinematics,
        bevy::prelude::With<ambition_platformer2d::platformer::markers::PrimaryPlayer>,
    >,
    mut act: bevy::prelude::Query<&mut SanicActState>,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
) {
    let Ok(kin) = player.single() else {
        return;
    };
    for mut state in &mut act {
        while let Some(&marker_x) = SPEED_MARKER_XS.get(state.next_milestone) {
            if kin.pos.x < marker_x {
                break;
            }
            let message = if state.next_milestone % 2 == 0 {
                ambition_platformer2d::sfx::SfxMessage::Dash { pos: kin.pos }
            } else {
                ambition_platformer2d::sfx::SfxMessage::Jump { pos: kin.pos }
            };
            // H2/I3: the COURSE's. A milestone is the room announcing that the
            // runner passed it — the room's event, not the runner's, and not the
            // host's either.
            sfx.write_from(provider::SANIC_EXPERIENCE, message);
            state.next_milestone += 1;
        }
    }
}

