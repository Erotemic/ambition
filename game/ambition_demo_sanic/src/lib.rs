/// Register Sanic's authored definitions in one Bevy `App`: the character
/// fragment and the provider-indexed music/SFX fragments. Both
/// [`SanicDemoContentPlugin`] (Startup-driven) and
/// [`provider::SanicExperiencePlugin`] (shell-activation-driven) call this.
///
/// The registered App-local resources are the sole composition authority.
/// Consumers receive the assembled catalog through Bevy resources.
pub fn install_sanic_content(app: &mut App) {
    use ambition_platformer2d::audio::catalog::{AudioCatalogAppExt, AudioCatalogFragment};
    use ambition_platformer2d::characters::actor::character_catalog::{
        CharacterCatalogAppExt, CharacterCatalogFragment,
    };

    app.register_character_catalog_fragment(
        CharacterCatalogFragment::from_ron(
            provider::SANIC_EXPERIENCE,
            Some(SANIC_CHARACTER_ID),
            SANIC_CATALOG_RON,
        )
        .expect("Sanic character catalog should be valid"),
    );
    // §7.6: both forms through the one character seam. Each registration
    // publishes the prepared definition and demands its art.
    {
        use ambition_platformer2d::actors::character_runtime::CharacterDefinitionAppExt;
        use ambition_platformer2d::character::CharacterDefinition;
        // The sheet target, not the sheet file: `sanic_spritesheet.ron`
        // declares `target: "sanic"`, and the registry is keyed by target.
        // Each form also gets a voice: a registered-only character has no
        // catalog row for bark pools, and the Hall's ambient ticker skips
        // anyone with nothing to say. A yarn node still wins over these.
        for (id, display, sheet, voice) in [
            (
                SANIC_CHARACTER_ID,
                "Sanic",
                "sanic",
                [
                    "You're too slow. No offense. Some offense.",
                    "I don't fight. I arrive, and then I've left.",
                    "Momentum is just a promise you keep to yourself.",
                ],
            ),
            (
                SUPER_SANIC_CHARACTER_ID,
                "Super Sanic",
                "super_sanic",
                [
                    "The rings were the tutorial. I am the exam.",
                    "Gravity had one job and it has been reassigned.",
                    "I went so fast I met the version of me that was leaving.",
                ],
            ),
        ] {
            // The ability ceiling is real
            // (`ambition_platformer2d::characters::action_scheme::combat_actions`);
            // guarded by `persona_architecture`'s
            // `the_demo_body_cannot_trigger_a_single_move_from_its_own_smash_table`.
            app.register_character(
                CharacterDefinition::new(id, display, provider::SANIC_EXPERIENCE)
                    .with_sheet(sheet)
                    // THE ART IS THE BODY, as it is for Mary-O: the box, the quad
                    // and the quad's offset all follow from the sheet at ONE
                    // scale. Without it he stood in the engine's default 30x48
                    // box with his 128x128 frame squeezed into it (x 0.23, y 0.38)
                    // and his feet ~3.75 units above the floor.
                    .with_sprite_authored_body(sanic_world_per_pixel())
                    .with_voice(voice)
                    .with_moveset(smash_moveset::sanic_moveset()),
            );
        }
    }
    // The badnik is a character; its four placements name it.
    badnik::register_badnik_character(app);
    app.register_audio_catalog_fragment(
        AudioCatalogFragment::new(
            provider::SANIC_EXPERIENCE,
            Some(sanic_music_registry()),
            // Sanic authors the cues it emits (Dash, Jump). Declaring them
            // authorizes them for provider-relative SFX; an Ambition-only
            // bank id cannot resolve here.
            Some(ambition_platformer2d::audio::spec::SfxRegistry {
                sample_rate: 44_100,
                sfx: sanic_sfx_specs(),
            }),
        )
        .expect("Sanic audio catalogs should be valid"),
    );
    // The ring sheet is content, so register it here: it loads the same way
    // standalone or hosted (both add `SanicExperiencePlugin`). A prop is not
    // in the lean sanic asset catalog, so this mirrors Ambition's intro-prop
    // loader (insert-if-missing each frame). See smell #19.
    app.add_systems(bevy::prelude::Update, register_sanic_ring_prop_sheet);
    // The start-line legend names buttons, so it follows the bindings.
    // Registered with the content: it is about this room's signage.
    app.add_systems(bevy::prelude::Update, refresh_sanic_control_legend);

    // Sanic's mutable sim state joins the rollback contract here, before
    // either construction path fingerprints the App, so the schema
    // fingerprint includes these rows. A non-GGRS shell records metadata only.
    {
        use ambition_platformer2d::rollback::AmbitionRollbackApp;
        // `BallDash`/`BallDashInput` ride the player body, which `entity:body_kinematics`
        // already anchors.
        app.require_rollback::<SanicActState>("ambition_demo_sanic", "entity:sanic_mode_owner")
            .rollback_component_clone_probed::<ball_dash::BallDash>(
                "ambition_demo_sanic",
                "content.sanic_ball_dash",
                rollback_probes::ball_dash,
            )
            .rollback_component_clone_probed::<ball_dash::BallDashInput>(
                "ambition_demo_sanic",
                "content.sanic_ball_dash_input",
                rollback_probes::ball_dash_input,
            )
            .rollback_component_clone_probed::<SanicActState>(
                "ambition_demo_sanic",
                "content.sanic_act_state",
                rollback_probes::act_state,
            )
            .rollback_component_clone_probed::<SuperFormLatch>(
                "ambition_demo_sanic",
                "content.sanic_super_form_latch",
                rollback_probes::super_form_latch,
            )
            // A scattered ring rides its currency pickup, which
            // `CenteredAabb`/`PickupFeature` already anchor and snapshot, so only
            // its own component needs registering.
            .rollback_component_clone_probed::<ScatteredRing>(
                "ambition_demo_sanic",
                "content.sanic_scattered_ring",
                rollback_probes::scattered_ring,
            )
            // The overlay subtracts spent monitors from collision every frame,
            // so a rewind that does not restore the set disagrees with the
            // world about what is solid (same as Mary-O's broken bricks).
            .rollback_resource_clone_checksum::<monitors::SpentMonitors>(
                "ambition_demo_sanic",
                "content.sanic_spent_monitors",
                "bevy_ggrs clone snapshot + an order-independent checksum over the spent names",
                |spent| spent.checksum(),
            );
        // Dropped rings have no global id counter: each mints its identity
        // from the spawning player's own `SimIdCounter` (ADR 0030).
    }
}

/// Keep the animated `sanic_ring_prop` sheet in `GameAssets.props` so the
/// pickup renderer binds it. Insert-if-missing, not a one-shot latch: the
/// host's quality-scale reload rebuilds `GameAssets` and wipes props, and the
/// insert flips `GameAssets::is_changed()` so the prop-rebind pass runs. Does
/// nothing when no `GameAssets` exists (headless).
fn register_sanic_ring_prop_sheet(
    game_assets: Option<
        bevy::prelude::ResMut<ambition_platformer2d::sprite_sheet::game_assets::GameAssets>,
    >,
    config: Option<
        bevy::prelude::Res<ambition_platformer2d::sprite_sheet::game_assets::GameAssetConfig>,
    >,
    asset_server: Option<bevy::prelude::Res<bevy::prelude::AssetServer>>,
    layouts: Option<
        bevy::prelude::ResMut<bevy::prelude::Assets<bevy::prelude::TextureAtlasLayout>>,
    >,
) {
    let (Some(mut game_assets), Some(config), Some(asset_server), Some(mut layouts)) =
        (game_assets, config, asset_server, layouts)
    else {
        return;
    };
    if config.no_assets || game_assets.characters.props.contains_key(RING_SPRITE_KIND) {
        return;
    }
    if let Some(asset) =
        ambition_platformer2d::actors::character_sprites::load_prop_sheet_for_target(
            &asset_server,
            &mut layouts,
            &config.sprite_folder,
            RING_SPRITE_KIND,
            &ambition_platformer2d::sprite_sheet::character::SheetTuning::new(1.0, 2),
        )
    {
        game_assets
            .characters
            .props
            .insert(RING_SPRITE_KIND.to_string(), asset);
    }
}

