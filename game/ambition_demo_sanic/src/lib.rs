/// Pick the rev tier from the post-tap charge (`0..=1`): the three buckets land
/// on the three natural tap counts (`rev_per_tap` 0.4 → ~0.4, ~0.8, 1.0).
pub fn rev_tier_id(charge: f32) -> &'static str {
    if charge < 0.5 {
        SFX_REV_TIERS[0]
    } else if charge < 0.85 {
        SFX_REV_TIERS[1]
    } else {
        SFX_REV_TIERS[2]
    }
}

/// Visually authored distance markers. The floating marker platforms (in the
/// LDtk file) and the one-shot milestone SFX share this table so the eye and
/// ear measure the same positions instead of drifting as the speedway changes.
pub const SPEED_MARKER_XS: [f32; 5] = [808.0, 1608.0, 2600.0, 3608.0, 5000.0];

/// The signage id of the speedway's control legend (the sign at the start
/// line).
///
/// Match the suffix, not the whole string: the room prefixes label ids with
/// `sanic_`, and the renderer prefixes `owner_id` with `signage:{index}:`. No
/// other sign ends this way (the others are `loop`, `finish`, `marker_N`).
const LEGEND_LABEL_ID: &str = "start";

/// The legend, written from the live bindings.
///
/// `bindings` is the seat's live projection when there is a seat. `None` is
/// room generation, which has no settings or participant and can only speak
/// for the default preset.
fn control_legend(
    bindings: Option<&ambition_platformer2d::input::ActionBindings>,
    // A style cannot say "this seat is on a keyboard", so the device is passed.
    device: ambition_platformer2d::input::ActiveDevice,
) -> String {
    use ambition_platformer2d::input::Platformer2dInputActionMonolith as Action;

    let default_keys = ambition_platformer2d::input::KeyboardPreset::arrows_zxc().actions;
    let name = ambition_platformer2d::input::key_name;
    let label = |action: Action, fallback: bevy::prelude::KeyCode| {
        bindings
            .and_then(|bound| bound.label_for(&action, device))
            .unwrap_or_else(|| name(fallback).to_string())
    };
    format!(
        "START   {}: JUMP   DOWN+{}: REV   RELEASE DOWN: DASH   {}: SUPER",
        label(Action::Jump, default_keys.jump),
        label(Action::Attack, default_keys.attack),
        label(Action::Special, default_keys.special),
    )
}

/// Rewrite the speedway's legend from the seat's live bindings.
///
/// This runs at presentation time, because the room (and its sign) is built
/// before any settings are read. Without it, a remapped or non-default preset
/// shows keys that do nothing.
///
/// Cheap on a quiet frame: it asks for text only when the bindings or the
/// seat's pad change, and writes only when the text differs.
fn refresh_sanic_control_legend(
    bindings: Option<bevy::prelude::Res<ambition_platformer2d::input::SeatBindings>>,
    devices: Option<bevy::prelude::Res<ambition_platformer2d::input::SeatActiveDevices>>,
    mut labels: bevy::prelude::Query<(
        &ambition_platformer2d::render::rendering::WorldLabel,
        &mut bevy::prelude::Text2d,
    )>,
    // The room load spawns the label after the bindings first publish, so the
    // first frame a sign exists must write even if nothing changed.
    mut written: bevy::prelude::Local<bool>,
) {
    use bevy::prelude::DetectChanges;

    let Some(bindings) = bindings else { return };
    let moved = bindings.is_changed() || devices.as_ref().is_some_and(|d| d.is_changed());
    if *written && !moved {
        return;
    }
    let seat = ambition_platformer2d::input::ParticipantId::PRIMARY.slot();
    let device = devices.map_or_else(Default::default, |devices| devices.for_seat(seat));
    let wanted = control_legend(Some(bindings.for_seat(seat)), device);
    for (label, mut text) in &mut labels {
        if !label.owner_id.ends_with(LEGEND_LABEL_ID) {
            continue;
        }
        *written = true;
        if text.0 != wanted {
            text.0 = wanted.clone();
        }
    }
}

/// Build the Sanic showcase room: parse the demo's LDtk world (everything
/// spatial), then graft the code-generated loop route onto it. The loop stays
/// in code because LDtk cannot express its depth lanes and junctions. It
/// anchors on floor-chain vertices the level generator authors at
/// [`struct@LOOP_RAMP_START_X`]/[`struct@LOOP_RUNOUT_END_X`], and it panics if
/// the two files drift.
pub fn sanic_speedway() -> RoomSpec {
    let project = ambition_platformer2d::ldtk_map::LdtkProject::from_json_str(SPEEDWAY_WORLD_JSON)
        .expect("sanic_speedway.ldtk parses (regen: game/ambition_demo_sanic/tools/author_speedway_ldtk.py)");
    let room_set = project
        // Sanic authors only engine nouns (no game-specific converter), and
        // the call says so.
        .to_room_set_with_entry(
            SPEEDWAY_ROOM_ID,
            &ambition_platformer2d::ldtk_map::LdtkVocabulary::engine(),
        )
        .unwrap_or_else(|errors| panic!("sanic_speedway.ldtk converts to rooms: {errors:?}"));
    let mut room = room_set
        .rooms
        .into_iter()
        .find(|room| room.id == SPEEDWAY_ROOM_ID)
        .expect("the world file authors the sanic_speedway area");

    let loop_center = graft_loop_route(&mut room.world);
    room.metadata.mode = Some(SANIC_MODE.to_string());
    // Borrow Ambition's generated skybridge stack. The visible shell loads the
    // shared `GameAssets`; if those optional images are absent the renderer keeps
    // the deterministic clear-color + landmark geometry fallback.
    room.metadata.biome = Some("skybridge".to_string());
    room.metadata.visual_theme = Some("skybridge".to_string());
    room.metadata.visual_profile.id = Some("sanic_speedway".to_string());
    room.metadata.visual_profile.parallax_theme = Some("skybridge".to_string());

    // World-space labels turn the speedway into a ruler. They are ordinary room
    // debug labels rendered by the generic presentation face, not app-local UI.
    let mut labels = vec![
        (
            LEGEND_LABEL_ID.to_string(),
            // Room generation has no settings or seat, so it writes the
            // default preset's legend. [`refresh_sanic_control_legend`]
            // replaces it once a seat's real bindings exist.
            control_legend(None, Default::default()),
            ae::Vec2::new(300.0, FLOOR_TOP - 230.0),
        ),
        (
            "loop".to_string(),
            "LOOP".to_string(),
            ae::Vec2::new(loop_center.x, loop_center.y - LOOP_RADIUS - 36.0),
        ),
        (
            "finish".to_string(),
            "FINISH".to_string(),
            // Derived from `GOAL_X`, so the sign and the trigger cannot drift.
            ae::Vec2::new(GOAL_X, FLOOR_TOP - 300.0),
        ),
    ];
    labels.extend(SPEED_MARKER_XS.into_iter().enumerate().map(|(index, x)| {
        (
            format!("marker_{}", index + 1),
            format!("{x:.0}"),
            ae::Vec2::new(x, FLOOR_TOP - 280.0),
        )
    }));
    room.debug_labels = labels
        .into_iter()
        .map(|(id, text, position)| {
            ambition_platformer2d::world::rooms::Authored::new(
                format!("sanic_{id}"),
                text.clone(),
                ae::Aabb::new(position, ae::Vec2::splat(1.0)),
                ambition_platformer2d::world::debug_label::DebugLabel::new(
                    text,
                    position,
                    ambition_platformer2d::world::debug_label::DebugLabelKind::Custom,
                ),
            )
        })
        .collect();
    room
}

/// Act 2, the highway: ground that climbs and drops, a speed-gated split (the
/// sky bridge or the valley), two secrets, an upside-down tunnel, a halfpipe,
