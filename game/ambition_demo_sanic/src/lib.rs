/// The goal line of the course `world` lays out. It is inside the player's
/// reachable horizontal extent, not at the level's visual edge.
pub fn goal_x_of(world: &ae::World) -> f32 {
    goal_x_with(&crate::rules::sanic_rules().act, world)
}

/// The goal line of `world` under the act rules `act`.
pub fn goal_x_with(act: &crate::rules::Act, world: &ae::World) -> f32 {
    world.size.x - act.goal_from_end
}

/// Where an act's FINISH sign stands: over its goal line, 300 px above the
/// ground there. Derived from the course, so the sign and the trigger cannot
/// drift, and a course with other ground has its sign over that ground.
fn finish_sign(world: &ae::World) -> ae::Vec2 {
    let x = goal_x_of(world);
    let ground = scenery::ground_at(world, x).unwrap_or(world.size.y);
    ae::Vec2::new(x, ground - 300.0)
}

/// The act's score, from the numbers captured at the clear.
pub fn act_score(time: f32, rings: i32) -> i32 {
    let act = crate::rules::sanic_rules().act;
    let remaining = (act.par_seconds - time).max(0.0);
    (remaining * act.time_bonus_per_second as f32) as i32 + rings.max(0) * act.ring_bonus
}

/// Format a duration the way a results screen does.
pub fn act_time_text(seconds: f32) -> String {
    let whole = seconds.max(0.0) as i32;
    format!("{}:{:02}", whole / 60, whole % 60)
}

/// The clock the HUD shows while an act runs: minutes, seconds and
/// hundredths.
pub fn act_clock_text(seconds: f32) -> String {
    let hundredths = (seconds.max(0.0) * 100.0) as i32;
    format!("{}:{:02}.{:02}", hundredths / 6000, hundredths / 100 % 60, hundredths % 100)
}

/// The name of an act and its number, by its room (`acts` in the pack's
/// `sanic_rules.ron`). `None` for a room that is not an act.
pub fn act_title(room_id: &str) -> Option<(&'static str, u8)> {
    let acts = &crate::rules::sanic_rules().acts;
    let index = acts.iter().position(|act| act.room == room_id)?;
    Some((acts[index].title.as_str(), index as u8 + 1))
}

/// After the goal, the course drives him, not the player.
///
/// The goal line is `act.goal_from_end` (400 px) from the right edge. Without this he crosses at speed,
/// runs out of level, and dies during his results card.
///
/// Zero the control, not the velocity: he rides the surface-momentum kernel,
/// so a written `vel` is overwritten from his surface parameter next tick.
fn take_the_controls_at_the_goal(
    subject: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::markers::ControlledSubject>,
    >,
    time: bevy::prelude::Res<ambition_platformer2d::time::WorldTime>,
    act: bevy::prelude::Query<&SanicActState>,
    mut commands: bevy::prelude::Commands,
    mut dashes: bevy::prelude::Query<&mut ball_dash::BallDash>,
    mut models: bevy::prelude::Query<&mut ambition_platformer2d::actor::MotionModel>,
    mut kinematics: bevy::prelude::Query<&mut ae::BodyKinematics>,
    mut holds: bevy::prelude::Query<&mut ambition_platformer2d::characters::control::ControlHolds>,
) {
    let cleared = act
        .iter()
        .any(|state| matches!(state.phase, SanicActPhase::Cleared { .. }));
    let Some(entity) = subject.and_then(|subject| subject.0) else {
        return;
    };
    if !cleared {
        // Release only the act's own hold. Something else can hold Sanic at
        // the same time.
        ambition_platformer2d::characters::control::release_control_hold(
            &mut commands,
            entity,
            holds.get_mut(entity).ok().as_deref_mut(),
            ambition_platformer2d::characters::control::ControlHold::Sequence,
        );
        return;
    }
    // Hold the whole control frame, not only locomotion. Crouch is
    // `locomotion.y`, so zeroing only locomotion looks like a crouch release
    // to `capture_ball_dash_input` and fires a charged spin dash.
    ambition_platformer2d::characters::control::claim_control_hold(
        &mut commands,
        entity,
        ambition_platformer2d::characters::control::ControlHold::Sequence,
    );
    // Blanking stops new charge, but a stored charge fires on an edge, and
    // blanking makes that edge. Disarm it.
    if let Ok(mut dash) = dashes.get_mut(entity) {
        dash.charge = 0.0;
        dash.crouched = false;
    }

    // Dropping the stick is not enough: his friction covers the last 400px in
    // under a second. Brake the momentum state's tangential speed `v_t` (the
    // authority while riding; `vel` is derived). Damp `vel` too for the
    // airborne case, where it is the authority.
    let Ok(mut motion) = models.get_mut(entity) else {
        return;
    };
    // The rate is `act.outro_brake_per_second` in his rules file.
    let brake = crate::rules::sanic_rules().act.outro_brake_per_second;
    let keep = (1.0 - brake * time.sim_dt()).clamp(0.0, 1.0);
    if let ae::MotionModel::SurfaceMomentum(momentum) = &mut *motion {
        // A brake has no airborne answer (the kinematic velocity below
        // handles that), so ignore the `false` return.
        momentum.scale_tangential_speed(keep);
    }
    if let Ok(mut kin) = kinematics.get_mut(entity) {
        kin.vel.x *= keep;
    }
}

/// Crossing the goal clears the act.
///
/// Captures the time and rings at the clear. The results card reads those,
/// so a ring picked up during the outro cannot change the result.
pub fn clear_act_at_goal(
    player: bevy::prelude::Query<
        (
            bevy::prelude::Entity,
            &ae::BodyKinematics,
            &ambition_platformer2d::characters::actor::BodyWallet,
        ),
        ambition_platformer2d::platformer::markers::PrimaryPlayerOnly,
    >,
    mut act: bevy::prelude::Query<&mut SanicActState>,
    // The goal of the room the runner is in. The clear burst is drawn in
    // that live room.
    rooms: ambition_platformer2d::world::rooms::LiveRoomSpecs,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
    mut vfx: ambition_platformer2d::vfx::VfxWriter,
) {
    let Ok((runner, kin, wallet)) = player.single() else {
        return;
    };
    let Some(spec) = rooms.spec_of(runner) else {
        return;
    };
    let goal = goal_x_of(&spec.world);
    for mut state in &mut act {
        if !matches!(state.phase, SanicActPhase::Running) || kin.pos.x < goal {
            continue;
        }
        state.phase = SanicActPhase::Cleared {
            time: state.elapsed,
            rings: wallet.balance,
            dwell: crate::rules::sanic_rules().act.clear_dwell,
        };
        vfx.for_room(rooms.live().of(runner)).write(crate::rules::sanic_rules().effects.act_clear.at(kin.pos));
        // H2/I3: the act's fanfare belongs to the course, not to the runner or
        // the host.
        sfx.write_from(
            provider::SANIC_EXPERIENCE,
            ambition_platformer2d::sfx::SfxMessage::Play {
                id: ambition_platformer2d::sfx::SfxId::from_static(SFX_TRANSFORM),
                pos: kin.pos,
            },
        );
    }
}

/// Once the results have been read, the act goes where its room says.
///
/// A room that names a `next_room` (an authored LDtk level field) leads there:
/// the speedway leads to the highway, then to the dark act and back. The trip is the
/// engine's [`Departure`](ambition_platformer2d::session::Departure) on the
/// mode owner, which keeps asking until the room changes and replays this room
/// if it never does, or if the room names nowhere to go.
///
/// Arriving restarts the act (`begin_act_on_arrival`). A trip that ends in the
/// same room (a replay) restarts it here.
pub fn cycle_act_after_clear(
    time: bevy::prelude::Res<ambition_platformer2d::time::WorldTime>,
    mut acts: bevy::prelude::Query<(
        &mut SanicActState,
        &mut ambition_platformer2d::session::Departure,
    )>,
) {
    for (mut state, mut departure) in &mut acts {
        let SanicActPhase::Cleared { dwell, .. } = &mut state.phase else {
            continue;
        };
        let reading_the_card = *dwell > 0.0;
        *dwell -= time.sim_dt();
        if *dwell > 0.0 {
            continue;
        }
        if reading_the_card {
            departure.leave(ambition_platformer2d::session::Destination::NextRoom);
        } else if !departure.is_leaving() {
            *state = SanicActState::default();
        }
    }
}

/// An act that arrives in a room starts over there: its clock, its milestones
/// and its results. The room it is in, and whether it has just arrived, is the
/// engine's `ModeVisit` on the same owner. The first room has a sound.
pub fn begin_act_on_arrival(
    mut acts: bevy::prelude::Query<(
        &mut SanicActState,
        &ambition_platformer2d::session::ModeVisit,
    )>,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
) {
    use ambition_platformer2d::session::Arrival;
    for (mut state, visit) in &mut acts {
        if visit.arrival() == Arrival::First {
            // Audible confirmation that the shell drains the standard
            // SfxMessage seam at room entry. H2/I3: the course's sound, by name.
            // `write_global` would make it the host's.
            sfx.write_from(
                provider::SANIC_EXPERIENCE,
                ambition_platformer2d::sfx::SfxMessage::Dash {
                    pos: ae::Vec2::ZERO,
                },
            );
        }
        if visit.arrival() != Arrival::Staying {
            *state = SanicActState::default();
        }
    }
}

/// Value projections for this demo's rollback state, like Mary-O's
/// `rollback_probes`.
///
/// f32 goes through `to_bits`. A rounding checksum calls two timelines equal
/// one ulp apart, and one ulp of a dash charge is one frame of launch speed.
mod rollback_probes {
    use super::*;

    pub(super) fn ball_dash(dash: &ball_dash::BallDash) -> u64 {
        (dash.charge.to_bits() as u64)
            ^ ((dash.crouched as u64) << 33)
            ^ ((dash.contact_grace.to_bits() as u64) << 1).rotate_left(11)
    }

    /// Captured input is rollback state, and its edges matter. A rewind that
    /// restores the charge but not `crouch_released` re-runs the launch frame
    /// with the edge consumed, so the timelines disagree on whether the dash
    /// fired.
    pub(super) fn ball_dash_input(input: &ball_dash::BallDashInput) -> u64 {
        (input.crouch_held as u64)
            | ((input.crouch_released as u64) << 1)
            | ((input.rev_pressed as u64) << 2)
            | ((input.grounded_at_capture as u64) << 3)
    }

    pub(super) fn act_state(state: &SanicActState) -> u64 {
        let phase = match state.phase {
            SanicActPhase::Running => 1,
            SanicActPhase::Cleared { time, rings, dwell } => {
                2 ^ ((time.to_bits() as u64) << 8)
                    ^ ((rings as u32 as u64) << 24).rotate_left(5)
                    ^ ((dwell.to_bits() as u64) << 1).rotate_left(29)
            }
        };
        (state.elapsed.to_bits() as u64)
            ^ phase.rotate_left(17)
            ^ ((state.next_milestone as u64) << 48)
    }

    pub(super) fn super_form_latch(latch: &SuperFormLatch) -> u64 {
        latch.0 as u64
    }

    pub(super) fn scattered_ring(ring: &ScatteredRing) -> u64 {
        (ring.vel.x.to_bits() as u64)
            ^ ((ring.vel.y.to_bits() as u64) << 32)
            ^ ((ring.lock.to_bits() as u64) << 1).rotate_left(13)
            ^ ((ring.life.to_bits() as u64) << 1).rotate_left(41)
    }
}
