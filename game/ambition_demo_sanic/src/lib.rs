/// The act's live state, owned by the mode. It rides a `ModeScopedEntity`, so
/// leaving the Sanic rooms tears it down through the engine's lifetime-scope
/// vocabulary rather than a bespoke reset.
#[derive(bevy::prelude::Component, Clone, Copy, Debug, Default, PartialEq)]
pub struct SanicActState {
    /// Seconds the act has been running (sim clock, so bullet-time slows it).
    pub elapsed: f32,
    /// Running or cleared. The clock stops on a clear, so the elapsed time
    /// becomes the result.
    pub phase: SanicActPhase,
    /// Next index in [`SPEED_MARKER_XS`] that should emit its one-shot progress
    /// cue. Mode-scoped with the act, so leaving and re-entering the demo resets
    /// the audible ruler without a global resource leak.
    pub next_milestone: usize,
    /// Which room of the session's room set this act is being run in. An act
    /// that finds itself in a different room has ARRIVED in the next one, and
    /// starts over there (`begin_act_on_arrival`).
    pub room: Option<usize>,
}

/// Where the act is. `Cleared` holds the numbers the results card reads,
/// captured at the clear, so rings picked up during the outro do not change
/// the result.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub enum SanicActPhase {
    #[default]
    Running,
    Cleared {
        time: f32,
        rings: i32,
        /// Seconds the results card has left before the act restarts.
        dwell: f32,
    },
}

/// Sanic's level rules. One system list; the constructor decides gating:
/// [`SanicRulesPlugin::hosted`] when Ambition hosts the demo beside its own
/// rooms, [`SanicRulesPlugin::global`] when the demo is the game.
pub struct SanicRulesPlugin {
    hosted: bool,
}

impl SanicRulesPlugin {
    /// Ambition hosts this demo: every rule sleeps outside the Sanic rooms.
    pub fn hosted() -> Self {
        Self { hosted: true }
    }

    /// The demo IS the game: the rules run unconditionally.
    pub fn global() -> Self {
        Self { hosted: false }
    }
}

impl Plugin for SanicRulesPlugin {
    fn build(&self, app: &mut App) {
        // The plugin owns its message channels and shared resources. A full
        // app registers these through the engine plugins; a thin rules-only
        // harness may not. `add_message`/`init_resource` are idempotent.
        app.add_message::<ambition_platformer2d::sfx::OwnedSfxMessage>();
        app.add_message::<ambition_platformer2d::vfx::VfxMessage>();
        app.add_message::<ambition_platformer2d::damage::WalletShieldSpent>();
        app.add_message::<ambition_platformer2d::world::rooms::RoomLoaded>();
        // The act cycle restarts the room on a clear, like Mary-O's level
        // cycle.
        app.add_message::<ambition_platformer2d::actors::session::reset::RoomReplayRequested>();
        // The monitor re-arm reads the admitted replay. A system that reads an
        // unregistered message fails parameter validation and is dropped, so
        // register it here and harnesses need not know.
        app.add_message::<ambition_platformer2d::combat::events::RoomReplayAdmitted>();
        // Sanic's death rules (ADR 0033): no interlude (a speed game loses a
        // run instantly), and the act restarts when nobody is left in play.
        // This must be stated: the engine default is `Never`, which suits a
        // versus stage but leaves a pit reset doing nothing. Standalone, these
        // are the binary's rules, so a rules-only harness can use an untagged
        // fixture room.
        {
            use ambition_platformer2d::combat::death_rules::DeathRulesAppExt as _;
            app.declare_death_rules(
                if self.hosted {
                    ambition_platformer2d::combat::death_rules::DeathRulesScope::Mode(SANIC_MODE)
                } else {
                    ambition_platformer2d::combat::death_rules::DeathRulesScope::EveryRoom
                },
                ambition_platformer2d::combat::death_rules::DeathRules::replay_level_after(0.0),
            );
        }
        app.init_resource::<ambition_platformer2d::world::FeatureEcsWorldOverlay>();
        use bevy::prelude::IntoScheduleConfigs;
        let sim = ambition_platformer2d::platformer::schedule::SimScheduleExt::sim_schedule(app);
        app.init_resource::<ball_dash::BallDashTuning>();
        // Sanic's half of a body reset (round boundary, respawn, and so on).
        // Not mode-gated: it fires only on `BodyRestarted` and touches only
        // Sanic's components, so it is inert for other bodies, and a gate would
        // disable it on the crossover stage that needs it.
        app.add_observer(ball_dash::clear_ball_dash_on_restart);
        // Utility is D in the classic preset. The gate's clear keeps that press
        // from also toggling a host flight ability.
        let sanic_pre_gate = (
            ball_dash::attach_ball_dash,
            declare_sanic_techniques,
            // After a clear the goal takes the stick and brakes him, so he
            // does not coast off the end during his results card.
            take_the_controls_at_the_goal,
        )
            .chain()
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::PlayerInput)
            .after(ambition_platformer2d::actors::avatar::ControlledBrainTick)
            .before(ambition_platformer2d::actors::avatar::WornControlGateSet);
        // After the gate: read the rev and transform from the technique edges
        // the gate resolved. This runs in `WorldPrep`, where the gate is,
        // because the gate must run after both control publications (D202).
        // Pinning `PlayerInput` here would create a schedule cycle.
        let sanic_post_gate = (
            ball_dash::capture_ball_dash_input,
            toggle_sanic_form,
        )
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::WorldPrep)
            .after(ambition_platformer2d::actors::avatar::WornControlGateSet);
        if self.hosted {
            app.add_systems(
                sim,
                sanic_pre_gate.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                sanic_post_gate.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
        } else {
            app.add_systems(sim, sanic_pre_gate);
            app.add_systems(sim, sanic_post_gate);
        }
        // The marker is derived from identity and room: leaving the Sanic
        // rooms removes the shield even if the same persona stays selected,
        // because no ring-scatter consumer runs there.
        app.add_systems(
            sim,
            sync_sanic_wallet_shield
                .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::PlayerInput)
                // Order against `Persona`, the contract, not against
                // `apply_worn_character_gameplay`, which may be renamed.
                .after(ambition_platformer2d::platformer::schedule::PlayerInputSet::Persona)
                .before(ambition_platformer2d::damage::PlayerHitResolutionSet),
        );

        // The ball dash is a rule: it exists only while the Sanic mode is live.
        // Effects run after PlayerInput captured the technique. `tick_ball_dash`
        // precedes `tick_rolling`, so a launch cannot un-ball in the same frame.
        let rules = (
            spawn_sanic_mode_owner,
            begin_act_on_arrival,
            tick_sanic_act,
            ball_dash::tick_ball_dash,
            ball_dash::tick_rolling,
            // Project the roll authority (`Rolling`) onto the anim fact after
            // both the launch (insert) and the stand-up (remove) have settled,
            // so the looping `ball` row tracks the physical ball for the frame.
            ball_dash::mirror_ball_anim_fact,
            // His transformation numbers ride his body, so the engine beat
            // reads authored feel rather than a default.
            ensure_sanic_transform_beat_policy,
            // The super form's derived traits (invincibility + sparkles) track
            // the worn identity every frame — toggle- and monitor-agnostic.
            sync_super_form_traits,
            // Braking scrape on the skid onset (reads the published skid fact).
            emit_sanic_skid_sfx,
            // The goal, then the cycle: a clear captured this frame must be
            // read by the card before the dwell can retire it.
            clear_act_at_goal,
            cycle_act_after_clear,
        )
            .chain()
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::GameplayEffects)
            // An act that asks to leave is carried out the same tick.
            .before(ambition_platformer2d::session::DepartureSet);
        // The super form states its traits before the engine runs them.
        //
        // This is an ordering, not an installation. `apply_contact_harm` is
        // absent from this game on purpose: `defeat_badniks` owns
        // destroy-on-touch (pop and bounce included), and two authorities must
        // not kill the same badnik. The engine owns expiry only.
        app.configure_sets(
            sim,
            ambition_platformer2d::actors::features::empowerment::EmpowermentExpiry
                .after(sync_super_form_traits)
                .before(emit_sanic_skid_sfx),
        );
        let milestone_sfx = emit_sanic_milestone_sfx
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::GameplayEffects);
        // The badnik defeat runs before the engine's shared body-contact-damage
        // pass so a stomp/roll never also hurts Sanic (the rule zeroes the
        // badnik's health that frame; the contact pass skips a dead attacker).
        let badniks = (
            // Declare dormancy before any brain ticks, so a far badnik does
            // not walk off a ledge while Sanic is at the start. The radius
            // comes from Sanic's top speed (see `BADNIK_WAKE_RADIUS`).
            badnik::tag_sanic_badniks,
            badnik::defeat_badniks,
        )
            .chain()
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::WorldPrep)
            .before(ambition_platformer2d::platformer::schedule::WorldPrepSet::ContactDamage);
        // The shared player resolver spends wallet armor before death and emits
        // the deterministic fact this Sanic presentation consumes.
        let ring_loss = scatter_rings_on_hit
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::PlayerSimulation)
            .after(ambition_platformer2d::damage::PlayerHitResolutionSet);
        // The scattered-ring burst runs between the coin magnet and the
        // collect: it owns each ring's position during the lock, so collect
        // sees the ring at its arc, not on the knocked-back body.
        let scatter_arc = arc_scattered_rings
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::FeatureCollection)
            .after(ambition_platformer2d::actors::features::PickupMagnetize)
            .before(ambition_platformer2d::actors::features::PickupCollect);
        // Monitor boxes: re-arm on (re)load, break on stomp/roll, tick the
        // speed-shoes grant. Broken monitors contribute to the overlay's
        // `removed_block_names` after the engine's per-frame rebuild clears it
        // (the same slot Mary-O's bricks and encounter lock walls take).
        let monitor_rules = (
            monitors::break_monitor_boxes,
            monitors::tick_speed_shoes,
        )
            .chain()
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::GameplayEffects);
        let monitor_overlay = monitors::contribute_broken_monitors_to_overlay
            .in_set(ambition_platformer2d::platformer::schedule::Platformer2dSimulationPhaseMonolith::WorldPrep)
            .after(ambition_platformer2d::platformer::schedule::FeatureWorldOverlaySet);
        // Aliased: the fully-qualified path wraps three ways at every call and
        // rustfmt then hides which type is being installed.
        use ambition_platformer2d::actors::session::reset::install_attempt_scoped;
        if self.hosted {
            app.add_systems(
                sim,
                rules.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                milestone_sfx.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                badniks.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                ring_loss.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                scatter_arc.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            app.add_systems(
                sim,
                monitor_rules.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
            // The re-arm is not in the monitor rules chain. It answers the
            // admitted replay, and the host anchors `ContentRoomReplayResetSet`
            // before its generic replay consumer: a pit death replays the room
            // in place and never emits `RoomLoaded`. `install_attempt_scoped`
            // pairs the resource with that slot in one statement.
            install_attempt_scoped::<monitors::SpentMonitors, _>(
                app,
                sim,
                ambition_platformer2d::runtime::in_mode(SANIC_MODE),
            );
            app.add_systems(
                sim,
                monitor_overlay.run_if(ambition_platformer2d::runtime::in_mode(SANIC_MODE)),
            );
        } else {
            app.add_systems(sim, rules);
            app.add_systems(sim, milestone_sfx);
            app.add_systems(sim, badniks);
            app.add_systems(sim, ring_loss);
            app.add_systems(sim, scatter_arc);
            app.add_systems(sim, monitor_rules);
            install_attempt_scoped::<monitors::SpentMonitors, _>(app, sim, || true);
            app.add_systems(sim, monitor_overlay);
        }
    }
}

/// Play the braking scrape on the frame the controlled body starts skidding.
///
/// The momentum integration publishes `BodyMotionFacts::skidding` every step.
/// A rising edge plays the scrape once per skid. One controlled body plays it,
/// so a `Local` edge latch is enough.
fn emit_sanic_skid_sfx(
    subject: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::markers::ControlledSubject>,
    >,
    mut was_skidding: bevy::prelude::Local<bool>,
    bodies: bevy::prelude::Query<(&ae::BodyMotionFacts, &ae::BodyKinematics)>,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
) {
    let subject = subject.and_then(|s| s.0);
    let skid = subject.and_then(|e| bodies.get(e).ok());
    let (skidding, pos) = skid.map_or((false, ae::Vec2::ZERO), |(facts, kin)| {
        (facts.skidding, kin.pos)
    });
    if skidding && !*was_skidding {
        // H2: the scrape belongs to the skidding body, not the session owner.
        // In a crossover they differ.
        if let Some(subject) = subject {
            sfx.write_for(
                subject,
                ambition_platformer2d::sfx::SfxMessage::Play {
                    id: ambition_platformer2d::sfx::SfxId::from_static(SFX_SKID),
                    pos,
                },
            );
        }
    }
    *was_skidding = skidding;
}

/// The id of Sanic's form toggle in the action scheme, and so the word on the
/// control: `ActionSpec::display` title-cases it to "Transform". No
/// `display_name` override, so the label cannot drift from the id.
const TRANSFORM_TECHNIQUE_ID: &str = "transform";

/// Sanic's technique declarations: their names and controls. One writer for
/// the whole set, upserting by slot, so no two systems race on
/// `ActorTechniques`.
fn declare_sanic_techniques(
    mut commands: bevy::prelude::Commands,
    subject: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::markers::ControlledSubject>,
    >,
    mut bodies: bevy::prelude::Query<
        Option<&mut ambition_platformer2d::characters::action_scheme::ActorTechniques>,
        bevy::prelude::With<ae::BodyKinematics>,
    >,
) {
    use ambition_platformer2d::entity_catalog::action_scheme as sch;

    let Some(entity) = subject.and_then(|subject| subject.0) else {
        return;
    };
    let Ok(techniques) = bodies.get_mut(entity) else {
        return;
    };
    let declared = [ball_dash::spin_dash_technique(), transform_technique()];
    match techniques {
        Some(mut techniques) => {
            // Skip the write in steady state; it would tick change detection
            // and re-derive the scheme every frame.
            let current: Vec<&sch::ActionSpec> = declared
                .iter()
                .filter_map(|spec| techniques.0.iter().find(|a| a.slot == spec.slot))
                .collect();
            if current.len() == declared.len()
                && current.iter().zip(declared.iter()).all(|(a, b)| *a == b)
            {
                return;
            }
            for spec in declared {
                techniques.0.retain(|a| a.slot != spec.slot);
                techniques.0.push(spec);
            }
        }
        None => {
            commands.entity(entity).try_insert(
                ambition_platformer2d::characters::action_scheme::ActorTechniques(
                    declared.to_vec(),
                ),
            );
        }
    }
}

/// The transformation's identity in the action scheme: a technique on the
/// mode-switch slot, which is where its input already lived.
fn transform_technique() -> ambition_platformer2d::entity_catalog::action_scheme::ActionSpec {
    use ambition_platformer2d::entity_catalog::action_scheme as sch;
    sch::ActionSpec {
        id: sch::ActionId::new(TRANSFORM_TECHNIQUE_ID),
        slot: sch::ControlSlot::Utility,
        display_name: None,
        visual: None,
        gate: sch::ActionGate::Technique(TRANSFORM_TECHNIQUE_ID.to_string()),
    }
}

/// Toggle the controlled body between the two catalog-authored Sanic forms.
///
/// The body declares `transform`, so the gate routes the press here and clears
/// the raw verb.
///
/// The super row authors the boosted movement, and `sync_super_form_traits`
/// derives the rest (invincibility, sparkles, badnik destroy-on-touch) from
/// the worn identity, so `WornCharacter` is the single authority. No timer.
///
/// It also drops the speed shoes: a wear replaces `MomentumParams`, so a
/// shoes grant would later restore a baseline saved from the other form.
fn toggle_sanic_form(
    mut commands: bevy::prelude::Commands,
    subject: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::markers::ControlledSubject>,
    >,
    mut bodies: bevy::prelude::Query<(
        &ambition_platformer2d::characters::action_scheme::ResolvedTechniqueEdges,
        &mut ambition_platformer2d::characters::actor::WornCharacter,
    )>,
) {
    let Some(entity) = subject.and_then(|subject| subject.0) else {
        return;
    };
    let Ok((edges, mut worn)) = bodies.get_mut(entity) else {
        return;
    };
    if !edges.pressed(TRANSFORM_TECHNIQUE_ID) {
        return;
    }

    let next = match worn.id() {
        SANIC_CHARACTER_ID => SUPER_SANIC_CHARACTER_ID,
        SUPER_SANIC_CHARACTER_ID => SANIC_CHARACTER_ID,
        _ => return,
    };
    // The transform sound fires from the worn-identity edge in
    // `sync_super_form_traits`. This only wears the form and drops any live
    // shoes.
    *worn = ambition_platformer2d::characters::actor::WornCharacter::new(next);
    commands.entity(entity).remove::<monitors::SpeedShoes>();
}

/// How often the super form's sparkle trail pulses (sim seconds).
const SUPER_SPARKLE_PERIOD: f32 = 0.14;
/// Radius of the sparkle orbit around the body centre (px).
const SUPER_SPARKLE_RADIUS: f32 = 15.0;
/// Upward bias of the sparkle ring (px, toward the torso) so the falling motes
/// hover around the body rather than pooling at the feet.
const SUPER_SPARKLE_RISE: f32 = 8.0;

/// Sanic's transformation beat is shorter and lighter than Mary-O's so it does not interrupt
/// the speed-focused demo.
fn ensure_sanic_transform_beat_policy(
    mut commands: bevy::prelude::Commands,
    bodies: bevy::prelude::Query<
        bevy::prelude::Entity,
        (
            bevy::prelude::With<ambition_platformer2d::platformer::markers::PrimaryPlayer>,
            bevy::prelude::Without<
                ambition_platformer2d::actors::features::transform_beat::TransformBeatPolicy,
            >,
        ),
    >,
) {
    for entity in &bodies {
        commands.entity(entity).try_insert(
            ambition_platformer2d::actors::features::transform_beat::TransformBeatPolicy {
                duration: 0.35,
                anim: ambition_platformer2d::sprite_sheet::character::CharacterAnim::Taunt,
                clock_scale: 0.5,
                untouchable: true,
            },
        );
    }
}

/// Derive super-form traits from the worn identity each simulation frame.
///
/// Movement speed is authored on the `super_sanic` catalog row. This system adds invulnerability
/// to contact and spike-strip damage plus the golden sparkle trail. Pits still reset the body
/// through `ResetCause::LeftTheWorld`. The derived traits revert when the super identity is removed.
fn sync_super_form_traits(
    time: bevy::prelude::Res<ambition_platformer2d::time::WorldTime>,
    mut sparkle_accum: bevy::prelude::Local<f32>,
    mut sparkle_orbit: bevy::prelude::Local<f32>,
    mut vfx: bevy::prelude::MessageWriter<ambition_platformer2d::vfx::VfxMessage>,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
    mut commands: bevy::prelude::Commands,
    mut players: bevy::prelude::Query<
        (
            bevy::prelude::Entity,
            &ambition_platformer2d::characters::actor::WornCharacter,
            &ae::BodyKinematics,
            Option<&SuperFormLatch>,
        ),
        bevy::prelude::With<ambition_platformer2d::platformer::markers::PrimaryPlayer>,
    >,
) {
    // `None` means no controlled player (the session has retired). Derive
    // invincibility and capture the emit position while the body is borrowed.
    let (worn_is_super, pos, body, was_super) = match players.single_mut() {
        Ok((body, worn, kinematics, latch)) => {
            let is_super = worn.id() == SUPER_SANIC_CHARACTER_ID;
            // Same fact as Mary-O's pocket quasar: cannot be hurt, destroys
            // what it runs through. Held, not timed: it lasts while he wears
            // the identity, whatever removes it.
            if is_super {
                commands.entity(body).try_insert(
                    ambition_platformer2d::actors::features::empowerment::Empowered::held(
                        SUPER_SANIC_SUPER_STATE,
                    ),
                );
            } else {
                commands
                    .entity(body)
                    .remove::<ambition_platformer2d::actors::features::empowerment::Empowered>();
            }
            (
                Some(is_super),
                kinematics.pos,
                Some(body),
                latch.is_some_and(|latch| latch.0),
            )
        }
        Err(_) => (None, ae::Vec2::ZERO, None, false),
    };

    // The transform sound comes from the worn-identity edge, so it fires once
    // whatever wore the form. With no controlled player the edge resolves to
    // `false`, so a session that ended super does not fire a phantom
    // detransform next session. The latch rides the body.
    let (cue, next_super) = super_form_edge(worn_is_super, was_super);
    if let Some(body) = body {
        commands.entity(body).try_insert(SuperFormLatch(next_super));
    }
    if let Some(to_super) = cue {
        // H2: attributed to the transforming body; falls back only when no
        // source was published.
        let transform = ambition_platformer2d::sfx::SfxMessage::Play {
            id: ambition_platformer2d::sfx::SfxId::from_static(if to_super {
                SFX_TRANSFORM
            } else {
                SFX_DETRANSFORM
            }),
            pos,
        };
        match body {
            // I3: with no body, fall back to the course that authored the cue,
            // not the session (under a shell host that is the launcher).
            Some(body) => sfx.write_for(body, transform),
            None => sfx.write_from(provider::SANIC_EXPERIENCE, transform),
        }
        // Becoming super only; losing the form gets no beat.
        if to_super {
            if let Some(body) = body {
                commands.entity(body).try_insert(
                    ambition_platformer2d::actors::features::transform_beat::TransformBeatRequested,
                );
            }
        }
    }

    // Sparkles only while a super body is present. Otherwise reset the
    // accumulator and orbit, so each super session starts at the same phase.
    if worn_is_super != Some(true) {
        *sparkle_accum = 0.0;
        *sparkle_orbit = 0.0;
        return;
    }
    *sparkle_accum += time.scaled_dt;
    if *sparkle_accum >= SUPER_SPARKLE_PERIOD {
        *sparkle_accum -= SUPER_SPARKLE_PERIOD;
        // Orbit the emit point around the body so the motes read as an aura
        // ring. The golden-angle step spreads pulses evenly; the upward bias
        // keeps the falling motes around the torso.
        *sparkle_orbit += 2.399_963; // golden angle, radians
        let ring = ae::Vec2::new(sparkle_orbit.cos(), sparkle_orbit.sin()) * SUPER_SPARKLE_RADIUS;
        vfx.write(ambition_platformer2d::vfx::VfxMessage::Burst {
            pos: pos + ring - ae::Vec2::new(0.0, SUPER_SPARKLE_RISE),
            count: 2,
            speed: 26.0,
            color: [1.0, 0.9, 0.4, 1.0],
            kind: ambition_platformer2d::vfx::ParticleKind::Spark,
        });
    }
}

/// Whether this body wore the super form last frame.
///
/// Rollback state, not a `Local<bool>`: the edge decides whether a
/// transformation beat plays, so a rewind must see it. It rides the body.
#[derive(bevy::prelude::Component, Clone, Copy, Debug, Default, PartialEq)]
pub struct SuperFormLatch(pub bool);

/// The super-form transform-cue edge.
///
/// `worn_is_super` is `None` when no player is controlled. Returns
/// `(cue, next_latch)`: `Some(true)` is a transform, `Some(false)` a
/// detransform, `None` no cue. With no controlled player the latch resets to
/// `false` and no cue fires.
fn super_form_edge(worn_is_super: Option<bool>, was_super: bool) -> (Option<bool>, bool) {
    match worn_is_super {
        None => (None, false),
        Some(is_super) if is_super != was_super => (Some(is_super), is_super),
        Some(_) => (None, was_super),
    }
}

/// Bring the act state into being the first frame the mode is live. Spawned
/// `spawn_mode_owner`, so the engine despawns it when the active room's mode
/// changes (no teardown code here) and names it for the rollback order.
fn spawn_sanic_mode_owner(
    mut commands: bevy::prelude::Commands,
    existing: bevy::prelude::Query<(), bevy::prelude::With<SanicActState>>,
    session: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::lifecycle::ActiveSessionScope>,
    >,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
) {
    use ambition_platformer2d::platformer::lifecycle::{SessionSpawnScope, SpawnSessionScopedExt};
    // Sleep when a session-scoped host has retired the session (at the
    // launcher): the room metadata may still read "sanic", but nothing should
    // own new state. With no `ActiveSessionScope` (Startup path, D-C tests)
    // the guard is inert.
    let session_live = session
        .as_ref()
        .map_or(true, |scope| scope.current().is_some());
    let spawn_scope = session
        .as_ref()
        .map_or(SessionSpawnScope::UNSCOPED, |scope| scope.spawn_scope());
    if session_live && existing.iter().next().is_none() {
        // Owned by the mode (survives in-session room changes) and by the
        // session (torn down on relaunch; a same-mode reload alone would leak
        // the act across launch → quit → relaunch).
        commands.spawn_mode_owner(spawn_scope, SANIC_MODE, SanicActState::default());
        // Audible confirmation that the shell drains the standard SfxMessage
        // seam at room entry. H2/I3: the course's sound, by name.
        // `write_global` would make it the host's.
        sfx.write_from(
            provider::SANIC_EXPERIENCE,
            ambition_platformer2d::sfx::SfxMessage::Dash {
                pos: ae::Vec2::ZERO,
            },
        );
    }
}

/// The act timer runs on the sim clock (`scaled_dt`), so bullet-time and pause
/// slow it exactly as they slow everything else — `WorldTime`, never `Res<Time>`.
fn tick_sanic_act(
    time: bevy::prelude::Res<ambition_platformer2d::time::WorldTime>,
    mut act: bevy::prelude::Query<&mut SanicActState>,
) {
    for mut state in &mut act {
        if matches!(state.phase, SanicActPhase::Running) {
            state.elapsed += time.scaled_dt;
        }
    }
}

/// Emit a small existing Ambition cue when the primary body crosses each
/// distance marker. This proves the shell drains the standard
/// [`ambition_platformer2d::sfx::SfxMessage`] seam; it is not a separate audio
/// stack.
fn emit_sanic_milestone_sfx(
    player: bevy::prelude::Query<
        &ae::BodyKinematics,
        bevy::prelude::With<ambition_platformer2d::platformer::markers::PrimaryPlayer>,
    >,
    mut act: bevy::prelude::Query<&mut SanicActState>,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
) {
    let Ok(kin) = player.single() else {
        return;
    };
    for mut state in &mut act {
        while let Some(&marker_x) = SPEED_MARKER_XS.get(state.next_milestone) {
            if kin.pos.x < marker_x {
                break;
            }
            let message = if state.next_milestone % 2 == 0 {
                ambition_platformer2d::sfx::SfxMessage::Dash { pos: kin.pos }
            } else {
                ambition_platformer2d::sfx::SfxMessage::Jump { pos: kin.pos }
            };
            // H2/I3: the course's sound, not the runner's or the host's.
            sfx.write_from(provider::SANIC_EXPERIENCE, message);
            state.next_milestone += 1;
        }
    }
}

