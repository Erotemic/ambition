/// Pick the rev tier from the post-tap charge (`0..=1`) at the rules'
/// `spin_dash.rev_tiers`.
pub fn rev_tier_id(charge: f32) -> &'static str {
    let [second, third] = ball_dash::spin_dash_tuning().rev_tiers;
    if charge < second {
        SFX_REV_TIERS[0]
    } else if charge < third {
        SFX_REV_TIERS[1]
    } else {
        SFX_REV_TIERS[2]
    }
}

/// The authored name of a distance marker is this prefix and its ordinal
/// (`distance_marker_1`). See [`distance_markers`].
pub const DISTANCE_MARKER_PREFIX: &str = "distance_marker_";

/// The x of each distance marker the room authors, west to east.
///
/// A marker is a `DebugLabel` in the room's LDtk, placed with its platform by
/// `tools/author_speedway_ldtk.py`. The label shows the distance and the
/// milestone cue sounds it, so the eye and the ear read one authored position,
/// and a room that authors no markers has none to sound.
pub fn distance_markers(room: &RoomSpec) -> Vec<f32> {
    let mut xs: Vec<f32> = room
        .debug_labels
        .iter()
        .filter(|label| label.name.starts_with(DISTANCE_MARKER_PREFIX))
        .map(|label| label.payload.position.x)
        .collect();
    xs.sort_by(f32::total_cmp);
    xs
}

/// A world file's text, as it is now.
pub fn world_text(world: &PackText) -> std::borrow::Cow<'static, str> {
    world.text().unwrap_or_else(|error| panic!("{error}"))
}

/// Build the Sanic showcase room from the demo's LDtk world. Everything spatial
/// is authored there: the painted ground (hills, pit, finish tower) and the
/// loop, a `SurfaceLoop` whose box is its circle, attached to the painted
/// floor, the distance markers and the start line's sign (`start_sign`), and
/// the level fields say its mode, biome and visual profile (the skybridge
/// parallax). This adds only the loop and finish signs, whose places come
/// from the loop and the goal.
pub fn sanic_speedway() -> RoomSpec {
    let project = ambition_platformer2d::ldtk_map::LdtkProject::from_json_str(&world_text(&SPEEDWAY_WORLD))
        .expect("sanic_speedway.ldtk parses (regen: game/ambition_demo_sanic/tools/author_speedway_ldtk.py)");
    let room_set = project
        // Sanic authors only engine nouns (no game-specific converter), and
        // the call says so.
        .to_room_set_with_entry(
            SPEEDWAY_ROOM_ID,
            &ambition_platformer2d::ldtk_map::LdtkVocabulary::engine(),
        )
        .unwrap_or_else(|errors| panic!("sanic_speedway.ldtk converts to rooms: {errors:?}"));
    let mut room = room_set
        .rooms
        .into_iter()
        .find(|room| room.id == SPEEDWAY_ROOM_ID)
        .expect("the world file authors the sanic_speedway area");

    let loop_top = loop_top(&room.world);

    // World-space signs, beside the distance markers the file authors. They are
    // ordinary room debug labels rendered by the generic presentation face, not
    // app-local UI.
    let signs = vec![
        (
            "loop".to_string(),
            crate::text::line("sign.loop"),
            ae::Vec2::new(loop_top.x, loop_top.y - 36.0),
        ),
        ("finish".to_string(), crate::text::line("sign.finish"), finish_sign(&room.world),
        ),
    ];
    room.debug_labels.extend(signs.into_iter().map(|(id, text, position)| {
        ambition_platformer2d::world::rooms::Authored::new(
            format!("sanic_{id}"),
            text.clone(),
            ae::Aabb::new(position, ae::Vec2::splat(1.0)),
            ambition_platformer2d::world::debug_label::DebugLabel::new(
                text,
                position,
                ambition_platformer2d::world::debug_label::DebugLabelKind::Custom,
            ),
        )
    }));
    monitors::dress_monitors(&mut room);
    scenery::dress_goal(&mut room);
    room
}

