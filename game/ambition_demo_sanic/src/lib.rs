//! Sanic-style demo content home.
//!
//! This crate depends only on the `ambition_platformer2d` facade crate. It is
//! the E9 engine-for-other-games oracle: a second platformer's content is
//! authored only through the umbrella surface. If a room here needs a type the
//! umbrella does not re-export, that is an engine leak, and it fails to
//! compile here.
//!
//! This crate holds the showcase course (rolling hills, a rideable loop,
//! springs, one-way platforms, a pit, monitors, and badniks) and the
//! mode-local rules, including milestone SFX. The spatial layout is in the
//! demo's own LDtk file (`assets/worlds/sanic_speedway.ldtk`, generated by
//! `tools/author_speedway_ldtk.py`). The loop route (depth lanes and
//! junctions, which LDtk cannot express) is grafted onto the loaded room in
//! [`sanic_speedway`]. The windowed shell loads the shared Ambition art tree
//! through the public facade, without an `ambition_app` dependency.

