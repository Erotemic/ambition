/// How many of the rings you were carrying actually scatter. The rest are gone.
///
/// A cap keeps a big purse from becoming a shower, and some loss makes
/// recovery matter.
const SCATTERED_RINGS_MAX: usize = 12;

/// Outward launch speed (px/s) a scattered ring bursts from the body with.
///
/// Reads as an explosion to chase, not a spill at your feet.
const SCATTER_BURST_SPEED: f32 = 900.0;

/// How many rings make up one shell of the burst. Past this, the next shell
/// launches slower, so a big purse bursts as an outer ring plus an inner one
/// instead of one over-dense circle.
const SCATTER_RINGS_PER_SHELL: usize = 6;

/// Speed multiplier for each shell inside the first — the classic halving,
/// softened slightly so the inner shell still clears the body.
const SCATTER_INNER_SHELL_SCALE: f32 = 0.55;

/// Downward pull (px/s²) that arcs a scattered ring back down, screen-relative
/// (the demo runs under normal screen gravity).
///
/// With the launch speed, this sizes the scatter: an arc about three tiles
/// high and a dozen wide, on the same screen.
const SCATTER_GRAVITY: f32 = 1400.0;

/// Fraction of speed a loose ring sheds per second in the air.
///
/// Without drag a horizontal ring never slows until it hits the floor, and
/// the outer rings leave the level.
const SCATTER_AIR_DRAG: f32 = 0.9;

/// Fraction of speed a scattered ring keeps when it bounces off geometry.
const SCATTER_RESTITUTION: f32 = 0.55;

/// How long (s) a scattered ring cannot be collected. It still bursts and
/// bounces; the hit costs something even while you stand in the spray.
///
/// This raises the running window, never replaces it: a hazard respawn arms a
/// longer one that must not be cut short.
pub(crate) const RING_LOSS_INVULN_S: f32 = 2.0;

const SCATTER_LOCK_S: f32 = 0.6;

/// How long (s) a scattered ring exists. Short enough that a big spray is
/// never fully recoverable.
const SCATTER_LIFE_S: f32 = 4.2;

/// A ring the player lost, mid-scatter: it bursts from the body, arcs down,
/// bounces, is untouchable for a moment, is collectible for the rest of its
/// short life, and then is gone.
///
/// Rollback-registered, like `BallDash`. Position is not stored here: the
/// ring's `CenteredAabb` is the one position authority, so a magnet nudge and
/// this arc compose.
#[derive(bevy::prelude::Component, Clone, Copy, Debug)]
pub struct ScatteredRing {
    /// Current scatter velocity (screen frame, px/s).
    pub vel: ae::Vec2,
    /// Seconds left before the ring can be collected.
    pub lock: f32,
    /// Seconds left before the ring vanishes.
    pub life: f32,
}

/// Bodies whose wallet shield Sanic's rule decides.
///
/// A body qualifies if it wears a Sanic persona, or already carries a
/// shield (the giveback for a body that stopped wearing Sanic).
/// [`BodyWalletShield`](ambition_platformer2d::characters::actor::BodyWalletShield)
/// has one writer, this file, so any shield is Sanic's. Other bodies (for
/// example George Booul on a Smash stage) are skipped. The persona check
/// cannot be a query filter, because `WornCharacter` holds an id, so it is
/// the first statement in the loop.
type SanicShieldBodies<'w, 's> = bevy::prelude::Query<
    'w,
    's,
    (
        bevy::prelude::Entity,
        &'static ambition_platformer2d::characters::actor::WornCharacter,
        bevy::prelude::Has<ambition_platformer2d::characters::actor::BodyWalletShield>,
    ),
    ambition_platformer2d::platformer::markers::PrimaryPlayerOnly,
>;

/// Whether this character id is one of Sanic's forms.
fn is_sanic_persona(id: &str) -> bool {
    matches!(id, "sanic" | "super_sanic")
}

/// The one system that decides whether a body's wallet absorbs a hit.
///
/// Yes for a Sanic persona in a Sanic room; no for the other bodies this rule
/// covers. `in_sanic_rooms` reads the active room's mode tag, not a
/// constructor flag, so hosted and standalone use one system.
///
/// Derived state, not an input edge: rebuilding it every frame avoids a
/// rollback latch and keeps the shared damage resolver content-agnostic.
fn sync_sanic_wallet_shield(
    mut commands: bevy::prelude::Commands,
    rooms: Option<
        ambition_platformer2d::platformer::lifecycle::SessionWorldRef<
            ambition_platformer2d::world::rooms::RoomSet,
        >,
    >,
    bodies: SanicShieldBodies<'_, '_>,
) {
    let in_sanic_rooms =
        rooms.is_some_and(|rooms| rooms.active_metadata().mode.as_deref() == Some(SANIC_MODE));
    for (entity, worn, shielded) in &bodies {
        let sanic_persona = is_sanic_persona(worn.id());
        // Not this ruleset's body (see `SanicShieldBodies`).
        if !sanic_persona && !shielded {
            continue;
        }
        let enabled = in_sanic_rooms && sanic_persona;
        match (enabled, shielded) {
            (true, false) => {
                commands
                    .entity(entity)
                    .try_insert(ambition_platformer2d::characters::actor::BodyWalletShield);
            }
            (false, true) => {
                commands
                    .entity(entity)
                    .remove::<ambition_platformer2d::characters::actor::BodyWalletShield>();
            }
            _ => {}
        }
    }
}

/// Present a wallet-shield spend as a classic ring burst.
///
/// The shared victim resolver decides survival before HP or death. This
/// system consumes its fact and owns only Sanic's spawning, VFX, and SFX.
pub fn scatter_rings_on_hit(
    mut commands: bevy::prelude::Commands,
    active_session: Option<
        bevy::prelude::Res<ambition_platformer2d::platformer::lifecycle::ActiveSessionScope>,
    >,
    mut spent: bevy::prelude::MessageReader<ambition_platformer2d::damage::WalletShieldSpent>,
    mut vfx: bevy::prelude::MessageWriter<ambition_platformer2d::vfx::VfxMessage>,
    mut sfx: ambition_platformer2d::sfx::BodySfxWriter,
    mut bodies: bevy::prelude::Query<
        (
            &ambition_platformer2d::platformer::sim_id::SimId,
            &mut ambition_platformer2d::platformer::sim_id::SimIdCounter,
            // The window the resolver already armed, which this game lengthens.
            Option<&mut ambition_platformer2d::characters::actor::BodyCombat>,
        ),
        ambition_platformer2d::platformer::markers::PrimaryPlayerOnly,
    >,
) {
    let Some(scope) =
        ambition_platformer2d::platformer::lifecycle::SessionSpawnScope::for_optional_active_session(
            active_session.as_deref(),
        )
    else {
        return;
    };

    for event in spent.read() {
        let Ok((player_id, mut counter, combat)) = bodies.get_mut(event.victim) else {
            // Should be unreachable (`ensure_sim_id` stamps the primary player
            // early). Report it: otherwise the currency vanishes silently.
            bevy::log::error_once!(
                "wallet shield spent {} on {:?}, but the victim has no \
                 SimId/SimIdCounter to mint scattered rings from — the spend is \
                 invisible to the player",
                event.amount,
                event.victim
            );
            continue;
        };
        // Lengthen the invulnerability window: the hit throws the purse
        // across half a screen, and the resolver's default is over before the
        // rings land. `WalletShieldSpent` leaves the expression to content.
        // Raise, never replace: a longer running window (a hazard respawn
        // arms 1.10s) must not be cut short.
        if let Some(mut combat) = combat {
            combat.damage_invuln_timer = combat.damage_invuln_timer.max(RING_LOSS_INVULN_S);
        }
        let scattered = (event.amount.max(0) as usize).min(SCATTERED_RINGS_MAX);
        if scattered == 0 {
            continue;
        }
        // Rings leave in evenly-spaced shells around the full circle. The
        // half-slot offset keeps the spray symmetric about both axes and stops
        // any ring launching straight down into the floor it is standing on.
        let shell_size = SCATTER_RINGS_PER_SHELL.min(scattered);
        for i in 0..scattered {
            // Rings burst from the body in every direction and arc under
            // gravity.
            let shell = i / shell_size;
            let t = ((i % shell_size) as f32 + 0.5) / shell_size as f32;
            let angle = std::f32::consts::TAU * t;
            let speed = SCATTER_BURST_SPEED * SCATTER_INNER_SHELL_SCALE.powi(shell as i32);
            let vel = ae::Vec2::new(angle.cos(), angle.sin()) * speed;
            let size = ae::Vec2::splat(RING_SIZE);
            let seq = counter.next();
            let ring_id = ambition_platformer2d::platformer::sim_id::SimId::spawned(player_id, seq);
            let authored = ambition_platformer2d::world::rooms::Authored {
                id: ring_id.as_str().to_string(),
                name: "ring".to_string(),
                aabb: ae::Aabb::new(event.pos, size * 0.5),
                payload: {
                    let mut spec =
                        ambition_platformer2d::entity_catalog::placements::PickupSpec::new(
                            ambition_platformer2d::entity_catalog::PickupKind::Currency {
                                amount: 1,
                            },
                        );
                    spec.sprite = Some(RING_SPRITE_KIND.to_string());
                    spec
                },
            };
            let ring = ambition_platformer2d::actors::features::ecs::spawn_static::spawn_pickup(
                &mut commands,
                scope,
                &authored,
            );
            // No `SimIdCounter` by hand: `SimId` requires it, so a ring is born
            // able to be descended from like every other identified entity.
            commands.entity(ring).insert((
                ring_id.clone(),
                ambition_platformer2d::platformer::construction::SpawnOrigin::Dynamic {
                    parent: player_id.clone(),
                    sequence: seq,
                },
                ScatteredRing {
                    vel,
                    lock: SCATTER_LOCK_S,
                    life: SCATTER_LIFE_S,
                },
                ambition_platformer2d::actors::features::PickupCollectLock,
            ));
        }

        vfx.write(ambition_platformer2d::vfx::VfxMessage::Burst {
            pos: event.pos,
            count: 24,
            // Matched to the rings' own launch speed, so the sparkle reads as the
            // same event and not a separate, smaller puff at the centre.
            speed: SCATTER_BURST_SPEED,
            color: [1.0, 0.86, 0.28, 1.0],
            kind: ambition_platformer2d::vfx::ParticleKind::Dust,
        });
        // H2: losing your rings is the struck body's cue.
        sfx.write_for(
            event.victim,
            ambition_platformer2d::sfx::SfxMessage::Play {
                id: ambition_platformer2d::sfx::SfxId::from_static(SFX_RING_LOSS),
                pos: event.pos,
            },
        );
    }
}

/// The whole life of a lost ring: burst, arc down, bounce, become
/// collectible, and expire.
///
/// Ordered `.after(magnetize_pickups).before(collect_ecs_pickups)`, so the
/// collector tests the ring at this frame's position. It adds to the ring's
/// `CenteredAabb` instead of owning it, so the magnet's pull and this arc
/// compose once the ring is collectible.
///
/// Deterministic: all state is the rollback-registered `ScatteredRing`, the
/// ring's AABB, the scaled sim dt, and static room geometry.
pub fn arc_scattered_rings(
    mut commands: bevy::prelude::Commands,
    time: bevy::prelude::Res<ambition_platformer2d::time::WorldTime>,
    // Optional: a `Single` that matches nothing skips the system, which would
    // freeze every ring mid-air. No geometry means nothing to bounce off.
    world: Option<
        ambition_platformer2d::platformer::lifecycle::SessionWorldRef<
            ambition_platformer2d::engine_core::RoomGeometry,
        >,
    >,
    mut rings: bevy::prelude::Query<(
        bevy::prelude::Entity,
        &mut ScatteredRing,
        &mut ae::CenteredAabb,
    )>,
) {
    let dt = time.scaled_dt;
    let solids = world.as_deref().map(|geometry| &geometry.0);
    for (entity, mut ring, mut aabb) in &mut rings {
        ring.life -= dt;
        if ring.life <= 0.0 {
            // Expired. Despawn instead of marking `Collected`: nobody took it.
            commands.entity(entity).despawn();
            continue;
        }
        ring.vel.y += SCATTER_GRAVITY * dt;
        ring.vel *= (1.0 - SCATTER_AIR_DRAG * dt).max(0.0);
        let (moved, bounced) = ring_step(solids, aabb.aabb(), ring.vel * dt);
        aabb.center += moved;
        if let Some(normal) = bounced {
            // Reflect and damp, so the ring chatters where it fell and settles.
            ring.vel = (ring.vel - normal * (2.0 * ring.vel.dot(normal))) * SCATTER_RESTITUTION;
        }
        if ring.lock > 0.0 {
            ring.lock -= dt;
            if ring.lock <= 0.0 {
                // Untouchable moment over: it is an ordinary currency pickup for
                // the rest of its life, on the shared collection path.
                commands
                    .entity(entity)
                    .remove::<ambition_platformer2d::actors::features::PickupCollectLock>();
            }
        }
    }
}

/// Move a ring by `delta` against the room's geometry, stopping at the first
/// surface it meets: a hill, a loop or a slope as much as a solid block.
///
/// Returns the displacement actually taken and the contact normal, if any.
fn ring_step(
    world: Option<&ae::World>,
    ring: ae::Aabb,
    delta: ae::Vec2,
) -> (ae::Vec2, Option<ae::Vec2>) {
    let (Some(world), true) = (world, delta != ae::Vec2::ZERO) else {
        return (delta, None);
    };
    // A ring is round: sweep it as the ball it is drawn as, by the sweep a
    // rider flies with. Boxes alone let a spray fall through every hill.
    let radius = (ring.max.x - ring.min.x) * 0.5;
    let center = (ring.min + ring.max) * 0.5;
    match ae::movement::sweep_ball(world, center, radius, delta, ae::Vec2::Y) {
        Some(hit) => (delta * hit.toi.clamp(0.0, 1.0), Some(hit.normal)),
        None => (delta, None),
    }
}

