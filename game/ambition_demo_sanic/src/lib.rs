/// Register Sanic's authored definitions in one Bevy `App`: the character
/// fragment and the provider-indexed music/SFX fragments, for
/// [`provider::SanicExperiencePlugin`].
///
/// The registered App-local resources are the sole composition authority.
/// Consumers receive the assembled catalog through Bevy resources.
pub fn install_sanic_content(app: &mut App) {
    use ambition_platformer2d::audio::catalog::AudioCatalogAppExt;

    // The cast is the pack's catalog: both of his forms and the badnik, each a
    // row. What a Sanic character that states no verbs can do as an actor is
    // a provider fact.
    pack::PACK
        .cast(provider::SANIC_EXPERIENCE, Some(SANIC_CHARACTER_ID))
        .with_actor_default_abilities(ambition_platformer2d::engine_core::AbilitySet::classic_actor(),
        )
        .register(app);
    // A build that reads his pack off disk plays an edit to his tuning from
    // the next session. His cast, audio and prop sheets are read here, once.
    app.add_plugins(ambition_platformer2d::content::live_reload::EmbeddedPackReloadPlugin {
        pack: &pack::PACK,
        // Each line is read where it is shown. The launcher row and the signs
        // are read once, when the launcher and the room are built.
        live: &[rules::SANIC_RULES_SCHEMA, text::SANIC_TEXT_SCHEMA],
        restated: Vec::new(),
    },
    );
    // His pack states his music and his SFX, his own Dash and Jump among
    // them. His moves name bank cues as well.
    app.register_audio_catalog_fragment(
        pack::PACK
            .audio(provider::SANIC_EXPERIENCE)
            .with_resident_sfx_bank(),
    );
    app.add_plugins(ambition_platformer2d::content::live_reload::EmbeddedPackReloadPlugin::audio(&pack::PACK, provider::SANIC_EXPERIENCE,
        ),
    );
    // The prop sheets (the ring, the monitors' boxes, the goal post) are the
    // pack's `data/prop_sheets.ron`. Registered here, they load the same way
    // standalone or hosted (both add `SanicExperiencePlugin`).
    {
        use ambition_platformer2d::game_assets::PropSheetsAppExt;
        app.register_prop_sheet_rows(
            ambition_platformer2d::sprite_sheet::prop_sheets::lowered_prop_sheets(pack::PACK.prepared(),
            )
                .expect("the demo's pack states its prop sheets (`data/prop_sheets.ron`)"),
        );
        app.add_plugins(ambition_platformer2d::content::live_reload::EmbeddedPackReloadPlugin::prop_sheets(&pack::PACK,
            ),
        );
        // Presentation reads sim state and writes render components, in
        // `Update` (Mary-O's `dress_power_blocks` says why not in the sim).
        // Asleep while another game is on screen in the hub: no Sanic room is
        // live then.
        app.add_systems(
            bevy::prelude::Update,
            bevy::prelude::IntoScheduleConfigs::run_if(
                (monitors::dress_monitor_boxes, scenery::dress_goal_posts),
                ambition_platformer2d::game_shell::shell_scope_is_on_screen_or_routing(provider::SANIC_EXPERIENCE,
                ),
            ),
        );
    }

    // Sanic's mutable sim state joins the rollback contract here, before
    // either construction path fingerprints the App, so the schema
    // fingerprint includes these rows. A non-GGRS shell records metadata only.
    {
        use ambition_platformer2d::rollback::AmbitionRollbackApp;
        // `BallDash`/`BallDashInput` ride the player body, which `entity:body_kinematics`
        // already anchors.
        app.require_rollback::<SanicActState>("ambition_demo_sanic", "entity:sanic_mode_owner")
            .rollback_component_clone_probed::<ball_dash::BallDash>(
                "ambition_demo_sanic",
                "content.sanic_ball_dash",
                rollback_probes::ball_dash,
            )
            .rollback_component_clone_probed::<ball_dash::BallDashInput>(
                "ambition_demo_sanic",
                "content.sanic_ball_dash_input",
                rollback_probes::ball_dash_input,
            )
            .rollback_component_clone_probed::<SanicActState>(
                "ambition_demo_sanic",
                "content.sanic_act_state",
                rollback_probes::act_state,
            )
            .rollback_component_clone_probed::<SuperFormLatch>(
                "ambition_demo_sanic",
                "content.sanic_super_form_latch",
                rollback_probes::super_form_latch,
            )
            // The roll is the flag the ball physics reads, so a rewind across
            // a launch must take it away.
            .rollback_component_clone::<ball_dash::Rolling>(
                "ambition_demo_sanic",
                "content.sanic_rolling",
            )
            // A scattered ring rides its currency pickup, which
            // `CenteredAabb`/`PickupFeature` already anchor and snapshot, so only
            // its own component needs registering.
            .rollback_component_clone_probed::<ScatteredRing>(
                "ambition_demo_sanic",
                "content.sanic_scattered_ring",
                rollback_probes::scattered_ring,
            )
            // The overlay subtracts spent monitors from collision every frame,
            // so a rewind that does not restore the set disagrees with the
            // world about what is solid (same as Mary-O's broken bricks).
            .rollback_resource_clone_checksum::<monitors::SpentMonitors>(
                "ambition_demo_sanic",
                "content.sanic_spent_monitors",
                "bevy_ggrs clone snapshot + an order-independent checksum over the spent names",
                |spent| spent.checksum(),
            );
        // Dropped rings have no global id counter: each mints its identity
        // from the spawning player's own `SimIdCounter` (ADR 0030).
    }
}

