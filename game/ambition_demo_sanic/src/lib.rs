//! Sanic-style demo content home.
//!
//! This crate intentionally depends only on the `ambition_platformer2d` facade crate. It is
//! the E9 engine-for-other-games ORACLE: a second platformer's content is
//! authored entirely through the umbrella surface, never by reaching into a
//! lower `ambition_*` crate or copying `game/ambition_app`'s dependency wall.
//! If authoring a room here needs a type the umbrella does not re-export, that
//! is a real engine leak — and it fails to compile HERE, which is the point.
//!
//! What lives here is the SHOWCASE COURSE — rolling hills, a rideable loop,
//! springs, one-way platforms, a pit, monitors, and badniks — plus the
//! mode-local rules that make progress legible through milestone SFX. The
//! SPATIAL layout is authored in the demo's own LDtk file
//! (`assets/worlds/sanic_speedway.ldtk`, generated by
//! `tools/author_speedway_ldtk.py`); the LOOP route (depth lanes + junctions,
//! which LDtk has no vocabulary for) is grafted onto the loaded room in
//! [`sanic_speedway`]. The windowed shell loads the shared Ambition art tree
//! through the public facade, so generated Sanic art and existing parallax /
//! block assets light up without an `ambition_app` dependency.

