MANIFEST = """// Generated by ambition_sprite2d_renderer. Do not edit by hand.
(
    target: "alice",
    image: "alice_portraits.png",
    frame_width: 256,
    frame_height: 320,
    default_clip: "default",
    clips: {
        "default": (duration_ms: 0, looping: false, frames: [(x: 0, y: 0, w: 256, h: 320)]),
        "speaking": (duration_ms: 105, looping: true, frames: [(x: 256, y: 0, w: 256, h: 320), (x: 512, y: 0, w: 256, h: 320)]),
    },
)
"""


def _sheet(root: Path) -> tuple[Path, Path]:
    src = root / "sprites"
    src.mkdir(parents=True)
    image = Image.new("RGBA", (768, 320), (0, 0, 0, 0))
    # Each cell its own colour, so a neighbour that bled in would show.
    for index, colour in enumerate([(255, 0, 0, 255), (0, 255, 0, 255), (0, 0, 255, 255)]):
        image.paste(Image.new("RGBA", (256, 320), colour), (index * 256, 0))
    image.save(src / "alice_portraits.png")
    (src / "alice_portraits.ron").write_text(MANIFEST)
    return src / "alice_portraits.ron", src / "alice_portraits.png"


def test_each_tier_fills_the_dialogue_box_and_potato_is_smaller_than_full(tmp_path: Path) -> None:
    ron, png = _sheet(tmp_path)
    sizes = {}
    for variant in g.VARIANTS:
        dst = tmp_path / f"sprites_{variant.suffix}" / "alice_portraits.ron"
        sizes[variant.suffix] = g.build_portrait_variant(ron, png, dst, variant)
        root = g.RonParser(dst.read_text()).parse()
        fw, fh = int(root.get("frame_width").raw), int(root.get("frame_height").raw)
        assert (fw, fh) == sizes[variant.suffix]
        assert fw >= g.PORTRAIT_BOX_PX[0] and fh >= g.PORTRAIT_BOX_PX[1], f"{variant.suffix}: {fw}x{fh} does not fill the box"
        with Image.open(dst.parent / "alice_portraits.png") as tier:
            assert tier.size == (3 * fw, fh), "the same grid at the tier's frame size"
            # The second clip's first frame is the green cell, whole.
            frame = [f for name, clip in root.get("clips").entries if name == "speaking" for f in clip.get("frames").items][0]
            x, y, w, h = (int(frame.get(k).raw) for k in "xywh")
            cell = tier.convert("RGBA").crop((x, y, x + w, y + h))
            assert cell.getcolors() == [(w * h, (0, 255, 0, 255))], f"{variant.suffix}: the rect is not the cell"
    assert sizes["0_5x"] == (128, 160)
    assert sizes["potato"][0] < 256 and sizes["potato"] == (104, 130), sizes


def test_the_box_is_the_largest_dialogue_portrait_box() -> None:
    """The generator's box is the largest `DialogLayoutProfile` portrait box."""
    text = (REPO / "game/ambition_content/src/presentation/dialog.rs").read_text()
    widths = [float(v) for v in re.findall(r"portrait_width:\s*([0-9.]+)", text)]
    heights = [float(v) for v in re.findall(r"portrait_height:\s*([0-9.]+)", text)]
    assert widths and heights, "the layout profiles name their portrait boxes"
    assert (max(widths), max(heights)) == g.PORTRAIT_BOX_PX
